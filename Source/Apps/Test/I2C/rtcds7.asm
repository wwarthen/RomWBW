;==================================================================================================
; DS1307 I2C DATE AND TIME UTILITY, VIA BF_I2C (RST 8)
;==================================================================================================
;
	.ECHO	"rtcds7\n"
;
DS7_DS1307	.EQU	11010000B		; DEVICE IDENTIFIER
DS7_W		.EQU	00000000B		; DEVICE WRITE
DS7_R		.EQU	00000001B		; DEVICE READ
;
DS7_READ	.EQU	(DS7_DS1307 | DS7_R)	; READ
DS7_WRITE	.EQU	(DS7_DS1307 | DS7_W)	; WRITE
;
	.ORG  100H
;
DS7_START:
	LD	(DS7_STK),SP		; SETUP A 
	LD	SP,DS7_LOC		; LOCAL STACK
;
	CALL	DS7_INIT		; INITIALIZE AND
	JR	NZ,DS7_ERR		; RETURN WITH STATUS
;
	LD	A,(FCB+1)		; GET FIRST COMMAND LINE CHAR 
	CP	' '			; COMPARE TO BLANK. IF SO NO
	JR	Z,DS7_ST0		; ARGUMENTS SO DISLAY TIME AND DATE
;
	LD	A,(FCB+1)		; GET FIRST CHAR 
	CP	'/'			; IS IT INDICATING AN ARGUMENT
	JR	NZ,DS7_ST0		; 
;
	LD	A,(FCB+2)		; GET NEXT CHARACTER
	CP	'D'			; 
	JR	NZ,DS7_ST1		; 
;
;	/D SET DATE
;
	JR	DS7_EXIT
;
DS7_ST1:
	LD	A,(FCB+2)		; GET NEXT CHARACTER
	CP	'T'			; 
	JR	NZ,DS7_ST2		; 
;
;	/T SET TIME
;
	JR	DS7_EXIT
;
DS7_ST2:
	LD	A,(FCB+2)		; GET NEXT CHARACTER
	CP	'S'			; 
	JR	NZ,DS7_ST3		; 
;
;	/S SET TIME AND DATE
;
	JR	DS7_EXIT
;
DS7_ST3:
;
;	UNREGOGNIZED ARGUMENT
;
	JR	DS7_EXIT
;
DS7_ST0:
	CALL   DS7_RDC			; READ CLOCK DATA INTO BUFFER
	OR	A
	JR	NZ,DS7_RDERR		; READ FAILED, REPORT AND SKIP DISPLAY
	CALL   DS7_DISP			; DISPLAY TIME AND DATE FROM BUFFER
	JR	DS7_EXIT
;
DS7_RDERR:
	CALL	DS7_RDMSG		; DISPLAY ERROR
;
DS7_EXIT:
	LD	SP,(DS7_STK)		; RESTORE STACK
	RET				; AND EXIT
;
DS7_ERR:
	CALL	I2C_INIERR		; DISPLAY ERROR
	JR	DS7_EXIT		; END EXIT
;
DS7_STK	.DW	2			; SAVE STACK
;
;-----------------------------------------------------------------------------
; RTC READ, VIA BF_I2C
;
; 1.	ISSUE SLAVE ADDRESS WITH START CONDITION AND WRITE STATUS
; 2.	OUTPUT THE ADDRESS TO ACCESS. (00H = START OF DS1307 REGISTERS)
; 3.	OUTPUT REPEAT START TO TRANSITION TO READ PROCESS
; 4.	ISSUE SLAVE ADDRESS WITH READ STATUS
; 5.	READ 7 BYTES STARTING AT ADDRESS PREVIOUSLY SET
; 6.	END READ WITH NON-ACKNOWLEDGE
; 7.	ISSUE STOP AND RELEASE BUS
;
DS7_RDC:
	LD	A,DS7_WRITE
	CALL	BF_START
	OR	A
	JR	NZ,DS7_RDC_ERR
;
	XOR	A			; REGISTER POINTER = 0
	CALL	BF_WRITE
	OR	A
	JR	NZ,DS7_RDC_ERR
;
	LD	A,DS7_READ
	CALL	BF_REPSTART
	OR	A
	JR	NZ,DS7_RDC_ERR
;
	LD	HL,DS7_BUF		; READ 7 BYTES INTO BUFFER
	LD	A,7
	LD	(DS7_RDC_CNT),A
DS7_RL1:
	PUSH	HL
	XOR	A			; NOT LAST BYTE, ACK
	CALL	BF_READ
	LD	C,L
	LD	B,A
	POP	HL
	LD	A,B
	OR	A
	JR	NZ,DS7_RDC_ERR
	LD	A,C
	LD	(HL),A
	INC	HL
	LD	A,(DS7_RDC_CNT)
	DEC	A
	LD	(DS7_RDC_CNT),A
	JR	NZ,DS7_RL1
;
	LD	A,1			; LAST BYTE, NACK
	CALL	BF_READ
	LD	C,L
	LD	B,A
	OR	A
	JR	NZ,DS7_RDC_ERR
	LD	A,C
	LD	(HL),A
;
	XOR	A
	CALL	BF_STOP
	XOR	A
	RET
;
DS7_RDC_ERR:
	PUSH	AF
	CALL	BF_STOP
	POP	AF
	RET
;
DS7_RDC_CNT	.DB	0
;
;-----------------------------------------------------------------------------
; DISPLAY CLOCK INFORMATION FROM DATA STORED IN BUFFER
;
DS7_DISP:
	LD	HL,DS7_CLKTBL
DS7_CLP:LD	C,(HL)
	INC	HL
	LD	D,(HL)
	CALL	DS7_BCD
	INC	HL
	LD	A,(HL)
	OR      A
	RET	Z
	CALL	COUT
	INC	HL
	JR	DS7_CLP
	RET
;
DS7_CLKTBL:
	.DB	04H, 00111111B, '/'
	.DB	05H, 00011111B, '/'
	.DB	06H, 11111111B, ' '
	.DB	02H, 00111111B, ':'
	.DB	01H, 01111111B, ':'
	.DB	00H, 01111111B, 00H
;
DS7_BCD:PUSH	HL
	LD      HL,DS7_BUF     	; READ VALUE FROM
	LD      B,0	   	; BUFFER, INDEXED BY A 
	ADD     HL,BC
	LD      A,(HL)
	AND     D	     	; MASK OFF UNNEEDED
	SRL     A
	SRL     A
	SRL     A
	SRL     A      
	ADD     A,30H
	CALL    COUT
	LD      A,(HL)    
	AND     00001111B
	ADD     A,30H
	CALL    COUT
	POP	HL
	RET
;
DS7_BUF:	.FILL	8,0	; BUFFER FOR TIME, DATE AND CONTROL

;-----------------------------------------------------------------------------
; INIT THE I2C BUS MASTER
;   EXIT: A=STATUS (0=OK), Z ON SUCCESS
;
DS7_INIT:
	CALL	BF_I2CDEV
	RET
;
;-----------------------------------------------------------------------------
; ERROR MESSAGE HELPERS
;
I2C_INIERR:
	PUSH	HL
	LD      HL,I2C_NODEV
	JR	I2C_PRTERR
;	
I2C_PRTERR:
	CALL	PRTSTR
	CALL	NEWLINE
	POP	HL	
	RET
;
I2C_NODEV	.DB	"NO DEVICE FOUND$"
;
;-----------------------------------------------------------------------------
; RTC READ STATUS-TO-MESSAGE DISPATCH
;   ENTRY: A=STATUS FROM DS7_RDC
;
DS7_RDMSG:
	PUSH	HL
	CP	1
	JR	Z,DS7_RDMSG_NAK
	CP	2
	JR	Z,DS7_RDMSG_BER
	CP	3
	JR	Z,DS7_RDMSG_BUSY
	CP	0FFH
	JR	Z,DS7_RDMSG_TO
	CP	ERR_NOHW
	JR	Z,DS7_RDMSG_NOHW
	LD	HL,DS7_RDUNK
	JR	I2C_PRTERR
DS7_RDMSG_NAK:
	LD	HL,DS7_RDNAK
	JR	I2C_PRTERR
DS7_RDMSG_BER:
	LD	HL,DS7_RDBER
	JR	I2C_PRTERR
DS7_RDMSG_BUSY:
	LD	HL,DS7_RDBUSY
	JR	I2C_PRTERR
DS7_RDMSG_TO:
	LD	HL,DS7_RDTO
	JR	I2C_PRTERR
DS7_RDMSG_NOHW:
	LD	HL,DS7_RDNOHW
	JR	I2C_PRTERR
;
DS7_RDNAK	.DB	"RTC READ: NAK$"
DS7_RDBER	.DB	"RTC READ: BUS ERROR$"
DS7_RDBUSY	.DB	"RTC READ: BUS NOT IDLE$"
DS7_RDTO	.DB	"RTC READ: TIMEOUT$"
DS7_RDNOHW	.DB	"RTC READ: NO I2C HARDWARE$"
DS7_RDUNK	.DB	"RTC READ: FAILED$"
;
;-----------------------------------------------------------------------------
;
#INCLUDE "bfi2c.inc"
#INCLUDE "i2ccpm.inc"
;
	.FILL	128
DS7_LOC:
;
	.END
