;	SN76489 SOUND DRIVER
;
;	WRITTEN BY: DEAN NETHERTON
;======================================================================
;
; SN74489 PSG CHIP NEEDS AN INPUT CLOCK FREQUENCY OF
; NO MORE THAN 4 MHZ.  THE CLOSEST THING THERE IS TO A STANDARD
; IS THE MSX FREQ OF 3.579545 MHZ.
;
; TODO:
; 1. PROVIDE SUPPORT FOR NOISE CHANNEL
; 2. DOES THIS WORK FOR FASTER CPUS? ONLY BEEN TESTED ON A Z80 7MHZ UNIT
;
;======================================================================
; CONSTANTS
;======================================================================
;

	DEVECHO	"SN MODE="
;
#IF (SNMODE == SNMODE_VGM)
SN_PORT_LEFT	.EQU	$C6	; PORTS FOR ACCESSING THE SN76489 CHIP (LEFT)
SN_PORT_RIGHT	.EQU	$C7	; PORTS FOR ACCESSING THE SN76489 CHIP (RIGHT)
	DEVECHO	"VGM"
#ENDIF
;
#IF (SNMODE == SNMODE_RC)
SN_PORT_LEFT	.EQU	$FF	; PORTS FOR ACCESSING THE SN76489 CHIP (LEFT)
SN_PORT_RIGHT	.EQU	$FB	; PORTS FOR ACCESSING THE SN76489 CHIP (RIGHT)
	DEVECHO	"RC"
#ENDIF
;
#IF (SNMODE == SNMODE_DUO)
SN7_PORT_LEFT	.EQU	$BE	; PORTS FOR ACCESSING THE SN76489 CHIP (LEFT)
SN7_PORT_RIGHT	.EQU	$BF	; PORTS FOR ACCESSING THE SN76489 CHIP (RIGHT)
	DEVECHO	"DUO"
#ENDIF
;
	DEVECHO	", IO_LEFT="
	DEVECHO	SN_PORT_LEFT
	DEVECHO	", IO_RIGHT="
	DEVECHO	SN_PORT_RIGHT
	DEVECHO	", CLOCK="
	DEVECHO	SN_CLK
	DEVECHO	" HZ\n"
;
SN_IDAT		.EQU	0
SN_TONECNT		.EQU	3	; COUNT NUMBER OF TONE CHANNELS
SN_NOISECNT		.EQU	1	; COUNT NUMBER OF NOISE CHANNELS
SN_CHCNT		.EQU	SN_TONECNT + SN_NOISECNT
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_SN	.EQU	$
;
	.DW	SIZ_SN			; MODULE SIZE
	.DW	SN_INITPHASE		; ADR OF INIT PHASE HANDLER
;
SN_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,SN_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,SN_INIT		; DO INIT
	RET				; DONE
;
#INCLUDE "audio.inc"
;
; BLINDLY RESET THE PSG AS SOON AS WE CAN AFTER BOOT BECAUSE IT
; DOES NOT RESET ITSELF AT POWER ON AND MAKES UGLY NOISE.
;
SN_PREINIT:
	JR	SN_RESET
;
SN_INIT:
	LD	IY, SN_IDAT		; POINTER TO INSTANCE DATA
	LD	BC, SN_FNTBL		; BC := FUNCTION TABLE ADDRESS
	LD	DE, SN_IDAT		; DE := SN INSTANCE DATA PTR
	CALL	SND_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED

	LD	DE,STR_MESSAGELT
	CALL	WRITESTR
	LD	A, SN_PORT_LEFT
	CALL	PRTHEXBYTE

	LD	DE,STR_MESSAGERT
	CALL	WRITESTR
	LD	A, SN_PORT_RIGHT
	CALL	PRTHEXBYTE

	CALL	SN_RESET
	XOR	A			; SIGNAL SUCCESS
	RET
;
;======================================================================
;	INITIALIZE DEVICE
;======================================================================
;
SN_INIT0:
;
#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)
	OR	%00001000		; SBC-V2-004+ CHANGE
	EZ80_IO
	OUT	(RTCIO),A		; TO HALF CLOCK SPEED
#ENDIF
;
	LD	HL,SN_REG_INIT		; POINT TO REG INIT TBL
	LD	B,SN_REG_CNT		; BYTES IN TABLE
SN_INIT1
	LD	A,(HL)
	INC	HL			; BUMP FOR NEXT TIME
	EZ80_IO
	OUT	(SN_PORT_LEFT), A	; WRITE LEFT PORT
	EZ80_IO
	OUT	(SN_PORT_RIGHT), A	; WRITE RIGHT PORT
	DJNZ	SN_INIT1		; LOOP TILL DONE
;
#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)
	AND	%11110111		; SBC-V2-004+ CHANGE TO
	EZ80_IO
	OUT	(RTCIO),A		; NORMAL CLOCK SPEED
#ENDIF
;
	RET
;
SN_REG_INIT:
	.DB	$80,$00			; TONE 1 FREQ (2 BYTES)
	.DB	$9F			; TONE 1 ATTENTUATION
	.DB	$A0,$00			; TONE 2 FREQ (2 BYTES)
	.DB	$BF			; TONE 2 ATTENTUATION
	.DB	$C0,$00			; TONE 3 FREQ (2 BYTES)
	.DB	$DF			; TONE 3 ATTENTUATION
	.DB	$E0			; NOISE CONTROL
	.DB	$FF			; NOISE ATTENTUATION
SN_REG_CNT	.EQU	$ - SN_REG_INIT
;
;======================================================================
; SN76489 DRIVER - SOUND ADAPTER (SND) FUNCTIONS
;======================================================================
;
SN_RESET:
	AUDTRACE(SNT_INIT)
;
	CALL	SN_INIT0		; HARDWARE INIT
;
	; RESET DEFAULTS IN CASE OF AN IN-PLACE HBIOS RESTART
	LD	HL,0
	LD	(SN_PENDING_PERIOD),HL
	LD	(SN_PENDING_DURATION),HL
	XOR	A
	LD	(SN_PENDING_VOLUME),A
;
	XOR	A
	RET

; BIT MAPPING
; SET TONE:
; 1 CC 0 PPPP (LOW)
; 0 0 PPPPPP (HIGH)

; 1 CC 1 VVVV

SN_VOLUME:
	AUDTRACE(SNT_VOL)
	AUDTRACE_L
	AUDTRACE_CR
	LD	A, L
	LD	(SN_PENDING_VOLUME), A

	XOR	A			; SIGNAL SUCCESS
	RET

SN_NOTE:
	LD	DE, SN_NOTETBL
	CALL	AUD_NOTE		; RETURNS PERIOD IN HL, FALL THRU
;
SN_PERIOD:
	AUDTRACE(SNT_PERIOD)
	AUDTRACE_HL
	AUDTRACE_CR
;
	LD	A,H			; IF ZERO - ERROR
	OR	L
	JR	Z,SN_PERIOD1
;
	LD	A,H			; MAXIMUM TONE PERIOD IS 10-BITS
	AND	11111100B		; ALLOWED RANGE IS 0001-03FF (1023)
	JR	NZ,SN_PERIOD1		; RETURN NZ IF NUMBER TOO LARGE
	LD	(SN_PENDING_PERIOD),HL	; SAVE AND RETURN SUCCESSFUL
	XOR	A			; SET SUCCESS
	RET
;
SN_PERIOD1:
	LD	HL,$FFFF		; REQUESTED PERIOD IS LARGER
	LD	(SN_PENDING_PERIOD),HL	; THAN PSG CAN SUPPORT, SO
	OR	$FF			; SET PERIOD TO $FFFF
	RET				; AND RETURN FAILURE
;
SN_PLAY:
	AUDTRACE(SNT_PLAY)
	AUDTRACE_D
	AUDTRACE_CR

	LD	A, (SN_PENDING_PERIOD + 1)
	CP	$FF
	JR	Z, SN_PLAY1		; PERIOD IS TOO LARGE, UNABLE TO PLAY
	CALL	SN_APPLY_VOL
	CALL	SN_APPLY_PRD

	XOR	A			; SIGNAL SUCCESS
	RET

SN_PLAY1:				; TURN CHANNEL VOL TO OFF AND STOP PLAYING
	LD	A, (SN_PENDING_VOLUME)
	PUSH	AF
	LD	A, 0
	LD	(SN_PENDING_VOLUME), A
	CALL	SN_APPLY_VOL
	POP	AF
	LD	(SN_PENDING_VOLUME), A

	OR	$FF			; SIGNAL FAILURE
	RET

SN_QUERY:
	LD	A, E
	CP	BF_SNDQ_CHCNT
	JR	Z, SN_QUERY_CHCNT

	CP	BF_SNDQ_PERIOD
	JR	Z, SN_QUERY_PERIOD

	CP	BF_SNDQ_VOLUME
	JR	Z, SN_QUERY_VOLUME

	CP	BF_SNDQ_DEV
	JR	Z, SN_QUERY_DEV

	OR	$FF			; SIGNAL FAILURE
	RET

SN_QUERY_CHCNT:
	LD	B, SN_TONECNT
	LD	C, SN_NOISECNT
	XOR	A
	RET

SN_QUERY_PERIOD:
	LD	HL, (SN_PENDING_PERIOD)
	XOR	A
	RET

SN_QUERY_VOLUME:
	LD	A, (SN_PENDING_VOLUME)
	LD	L, A
	LD	H, 0

	XOR	A
	RET

SN_QUERY_DEV:

	LD	B, SNDDEV_SN
	LD	DE, SN_PORT_LEFT 	; E WITH LEFT PORT
	LD	HL, SN_PORT_RIGHT	; L WITH RIGHT PORT

	XOR	A
	RET
;
;	UTIL FUNCTIONS
;

SN_APPLY_VOL:				; APPLY VOLUME TO BOTH LEFT AND RIGHT CHANNELS
	PUSH	BC			; D CONTAINS THE CHANNEL NUMBER
	PUSH	AF
	LD	A, D
	AND	$3
	RLCA
	RLCA
	RLCA
	RLCA
	RLCA
	OR	$90
	LD	B, A

	LD	A, (SN_PENDING_VOLUME)
	RRCA
	RRCA
	RRCA
	RRCA

	AND	$0F
	LD	C, A
	LD	A, $0F
	SUB	C
	AND	$0F
	OR	B			; A CONTAINS COMMAND TO SET VOLUME FOR CHANNEL

	AUDTRACE(SNT_REGWR)
	AUDTRACE_A
	AUDTRACE_CR

#IFDEF SBCV2004
	PUSH	AF
	LD	A,(HB_RTCVAL)
	OR	%00001000		; SBC-V2-004+ CHANGE
	EZ80_IO
	OUT	(RTCIO),A		; TO HALF CLOCK SPEED
	POP	AF
#ENDIF
	EZ80_IO
	OUT	(SN_PORT_LEFT), A
	EZ80_IO
	OUT	(SN_PORT_RIGHT), A

#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)
	AND	%11110111		; SBC-V2-004+ CHANGE TO
	EZ80_IO
	OUT	(RTCIO),A		; NORMAL CLOCK SPEED
#ENDIF

	POP	AF
	POP	BC
	RET

SN_APPLY_PRD:
	PUSH	DE
	PUSH	BC
	PUSH	AF
	LD	HL, (SN_PENDING_PERIOD)

	LD	A, D
	AND	$3
	RLCA
	RLCA
	RLCA
	RLCA
	RLCA
	OR	$80
	LD	B, A			; PERIOD COMMAND 1 - CONTAINS CHANNEL ONLY

	LD	A, L			; GET LOWER 4 BITS FOR COMMAND 1
	AND	$F
	OR	B			; A NOW CONTAINS FIRST PERIOD COMMAND

	AUDTRACE(SNT_REGWR)
	AUDTRACE_A
	AUDTRACE_CR

#IFDEF SBCV2004
	PUSH	AF
	LD	A,(HB_RTCVAL)
	OR	%00001000		; SBC-V2-004+ CHANGE
	EZ80_IO
	OUT	(RTCIO),A		; TO HALF CLOCK SPEED
	POP	AF
#ENDIF
	EZ80_IO
	OUT	(SN_PORT_LEFT), A
	EZ80_IO
	OUT	(SN_PORT_RIGHT), A

#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)
	AND	%11110111		; SBC-V2-004+ CHANGE TO
	EZ80_IO
	OUT	(RTCIO),A		; NORMAL CLOCK SPEED
#ENDIF

	LD	A, L			; RIGHT SHIFT OUT THE LOWER 4 BITS
	RRCA
	RRCA
	RRCA
	RRCA
	AND	$F
	LD	B, A

	LD	A, H
	AND	$3
	RLCA
	RLCA
	RLCA
	RLCA				; AND PLACE IN BITS 5 AND 6
	OR	B			; OR THE TWO SETS OF BITS TO MAKE 2ND PERIOD COMMAND

	AUDTRACE(SNT_REGWR)
	AUDTRACE_A
	AUDTRACE_CR

#IFDEF SBCV2004
	PUSH	AF
	LD	A,(HB_RTCVAL)
	OR	%00001000		; SBC-V2-004+ CHANGE
	EZ80_IO
	OUT	(RTCIO),A		; TO HALF CLOCK SPEED
	POP	AF
#ENDIF
	EZ80_IO
	OUT	(SN_PORT_LEFT), A
	EZ80_IO
	OUT	(SN_PORT_RIGHT), A

#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)
	AND	%11110111		; SBC-V2-004+ CHANGE TO
	EZ80_IO
	OUT	(RTCIO),A		; NORMAL CLOCK SPEED
#ENDIF

	POP	AF
	POP	BC
	POP	DE
	RET

SN_DURATION:
	LD	(SN_PENDING_DURATION),HL	; SET TONE DURATION
	XOR	A
	RET

SN_DEVICE:
	LD	D,SNDDEV_SN		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL UNIT
	LD	C,$00			; C := DEVICE TYPE
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,SN_PORT_LEFT		; L := BASE I/O ADDRESS
	XOR	A
	RET

SN_BEEP:
	JP	SND_BEEP		; DEFER TO GENERIC CODE IN HBIOS

SN_FNTBL:
	.DW	SN_RESET
	.DW	SN_VOLUME
	.DW	SN_PERIOD
	.DW	SN_NOTE
	.DW	SN_PLAY
	.DW	SN_QUERY
	.DW	SN_DURATION
	.DW	SN_DEVICE
	.DW	SN_BEEP
;
#IF (($ - SN_FNTBL) != (SND_FNCNT * 2))
	.ECHO	"*** INVALID SND FUNCTION TABLE ***\n"
	!!!!!
#ENDIF

SN_PENDING_PERIOD	.DW	0	; PENDING PERIOD (10 BITS)
SN_PENDING_VOLUME	.DB	0	; PENDING VOL (8 BITS -> DOWNCONVERTED TO 4 BITS AND INVERTED)
SN_PENDING_DURATION	.DW	0	; PENDING DURATION (16 BITS)

STR_MESSAGELT	.DB	"\r\nSN: LEFT IO=0x$"
STR_MESSAGERT	.DB	", RIGHT IO=0x$"

