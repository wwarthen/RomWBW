;
;==================================================================================================
; DLP-USB SERIAL DRIVER
;==================================================================================================
;
; THIS SERIAL DRIVER SUPPORTS THE DLP-USB DEVICE ON THE S100 SERIAL-IO
; BOARD.  NOTE THAT THE DLP USB DEVICE IS CONNECTED IN PARALLEL TO THE
; S100 SYSTEM.  IT DOES NOT ACTUALLY USE A TRUE SERIAL DATA STREAM
; EVEN THOUGH IT APPEARS AS SUCH TO THE USB-CONNECTED COMPUTER.
;
; STATUS BITS:				IDLE
;   7: 0=CHAR PENDING			1
;   6: 0=XMIT HOLDING REGISTER EMPTY	0
;   5-0: UNDEFINED
;
DLPSER_NONE	.EQU	0
DLPSER_DLP	.EQU	1
;
; PER DEVICE DATA OFFSETS IN CFG BLOCK
; BYTES 0-7 ARE STANDARD (SEE STD.ASM DRIVER CONFIG BLOCK STANDARD OFFSETS)
;
DLPSER_CFG_TYPE	.EQU	8		; DLPSER TYPE (BYTE)
DLPSER_CFG_STAT	.EQU	9		; STATUS PORT (BYTE)
DLPSER_CFG_DATA	.EQU	10		; DATA PORT (BYTE)
;
DLPSER_CFGSIZ	.EQU	11		; SIZE OF CFG TBL ENTRIES
;
DLPSERCFG	.EQU	SER_9600_8N1	; DLPSER: SERIAL LINE CONFIG
;
; ACCORDING TO THE S100 SERIAL-IO BOARD CONVENTIONS, THE PPI IS
; CONFIGURED FOR MODE 0 WITH A=INPUT, B=OUTPUT, C0-3=OUTPUT,
; C4-7=INPUT
;
DLPSER_PPICTL	.EQU	$AB
DLPSER_PPICFG	.EQU	%10011000
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_DLPSER	.EQU	$
;
	.DW	SIZ_DLPSER		; MODULE SIZE
	.DW	DLPSER_INITPHASE	; ADR OF INIT PHASE HANDLER
;
DLPSER_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,DLPSER_PREINIT	; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,DLPSER_INIT		; DO INIT
	RET				; DONE


;
DLPSER_PREINIT:
;
; SETUP THE DISPATCH TABLE ENTRIES
;
	LD	B,DLPSERCNT		; LOOP CONTROL
	XOR	A			; ZERO TO ACCUM
	LD	(DLPSER_DEV),A		; CURRENT DEVICE NUMBER
	LD	IY,DLPSER_CFG		; POINT TO START OF CFG TABLE
DLPSER_PREINIT0:
	PUSH	BC			; SAVE LOOP CONTROL
	CALL	DLPSER_INITUNIT		; HAND OFF TO GENERIC INIT CODE
	POP	BC			; RESTORE LOOP CONTROL
;
	LD	A,(IY+DLPSER_CFG_TYPE)	; GET THE DLPSER TYPE DETECTED
	OR	A			; SET FLAGS
	JR	Z,DLPSER_PREINIT2	; SKIP IT IF NOTHING FOUND
;	
	PUSH	IY			; CFG ENTRY ADDRESS
	POP	DE			; ... TO DE
	CALL	CIO_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED
	LD	(IY+CFG_UNIT),A		; RECORD HBIOS UNIT NUMBER ASSIGNED
;
DLPSER_PREINIT2:
	LD	DE,DLPSER_CFGSIZ	; SIZE OF CFG ENTRY
	ADD	IY,DE			; BUMP IY TO NEXT ENTRY
	DJNZ	DLPSER_PREINIT0		; LOOP UNTIL DONE
;	
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
; DLPSER UNIT INITIALIZATION ROUTINE
;
DLPSER_INITUNIT:
	CALL	DLPSER_DETECT		; DETECT IT
	LD	(IY+DLPSER_CFG_TYPE),A	; SAVE IN CONFIG TABLE
	OR	A			; SET FLAGS
	RET	Z			; ABORT IF NOTHING THERE
;
	; UPDATE WORKING DLPSER DEVICE NUM
	LD	HL,DLPSER_DEV		; POINT TO CURRENT UART DEVICE NUM
	LD	A,(HL)			; PUT IN ACCUM
	INC	(HL)			; INCREMENT IT (FOR NEXT LOOP)
	LD	(IY+CFG_DEVNUM),A	; UPDATE UNIT NUM
;	
	JP	DLPSER_INITDEV		; INIT DEVICE AND RETURN
;
;
;
DLPSER_INIT:
	LD	B,DLPSERCNT		; COUNT OF POSSIBLE DLPSER UNITS
	LD	IY,DLPSER_CFG		; POINT TO START OF CFG TABLE
DLPSER_INIT1:
	PUSH	BC			; SAVE LOOP CONTROL
	LD	A,(IY+DLPSER_CFG_TYPE)	; GET DLPSER TYPE
	OR	A			; SET FLAGS
	CALL	NZ,DLPSER_PRTCFG	; PRINT IF NOT ZERO
	POP	BC			; RESTORE LOOP CONTROL
	LD	DE,DLPSER_CFGSIZ	; SIZE OF CFG ENTRY
	ADD	IY,DE			; BUMP IY TO NEXT ENTRY
	DJNZ	DLPSER_INIT1		; LOOP TILL DONE
;
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
; DRIVER FUNCTION TABLE
;
DLPSER_FNTBL:
	.DW	DLPSER_IN
	.DW	DLPSER_OUT
	.DW	DLPSER_IST
	.DW	DLPSER_OST
	.DW	DLPSER_INITDEV
	.DW	DLPSER_QUERY
	.DW	DLPSER_DEVICE
	.DW	CIO_BLKIN
	.DW	CIO_BLKOUT
#IF (($ - DLPSER_FNTBL) != (CIO_FNCNT * 2))
	.ECHO	"*** INVALID DLPSER FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
;
;
DLPSER_IN:
	CALL	DLPSER_IST		; CHECK FOR CHAR PENDING
	JR	Z,DLPSER_IN		; WAIT FOR IT IF NECESSARY
	;IN	A,(DLPSER_DATA)		; READ THE CHAR
	LD	C,(IY+DLPSER_CFG_DATA)	; DATA PORT
	IN	E,(C)			; GET BYTE
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
;
;
DLPSER_IST:
	;IN	A,(DLPSER_STAT)		; READ LINE STATUS REGISTER
	LD	C,(IY+DLPSER_CFG_STAT)	; STATUS PORT
	IN	A,(C)			; GET STATUS
	CPL
	AND	%10000000		; ISOLATE DATA READY
	JP	Z,CIO_IDLE		; RETURN VIA IDLE PROCESSING
	LD	A,1			; SET A=1 TO SIGNAL 1 CHAR WAITING
	RET				; RETURN
;
;
;
DLPSER_OUT:
	CALL	DLPSER_OST		; CHECK FOR OUTPUT READY
	JR	Z,DLPSER_OUT		; WAIT IF NECESSARY
	;LD	A,E			; RECOVER THE CHAR TO WRITE
	;OUT	(DLPSER_DATA),A		; WRITE THE CHAR
	LD	C,(IY+DLPSER_CFG_DATA)	; DATA PORT
	OUT	(C),E			; SEND BYTE
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
;
;
DLPSER_OST:
	;IN	A,(DLPSER_STAT)		; READ LINE STATUS REGISTER
	LD	C,(IY+DLPSER_CFG_STAT)	; STATUS PORT
	IN	A,(C)			; GET STATUS
	CPL
	AND	%01000000 		; ISOLATE OUTPUT RDY
	JP	Z,CIO_IDLE		; RETURN VIA IDLE PROCESSING
	LD	A,1			; SET A=1 TO SIGNAL 1 BUFFER POSITION
	RET				; RETURN
;
;
;
DLPSER_INITDEV:
#IF (PLATFORM == PLT_SZ80)
	LD	A,(IY+DLPSER_CFG_DATA)	; GET THE DATA PORT
	CP	$AA			; IS THIS THE SERIAL I/O BOARD DLP DEVICE?
	JR	NZ,DLPSER_INITDEV1	; IF NOT, SKIP
	LD	A,DLPSER_PPICFG		; CONFIG 8255 PORTS
	OUT	(DLPSER_PPICTL),A	; WRITE CONTROL WORD
#ENDIF
DLPSER_INITDEV1:
	XOR	A			; NOTHING TO DO
	RET
;
;
;
DLPSER_QUERY:
	LD	DE,DLPSERCFG
	XOR	A
	RET
;
;
;
DLPSER_DEVICE:
	LD	D,CIODEV_DLPSER		; D := DEVICE TYPE
	LD	E,(IY+CFG_DEVNUM)	; E := DEVICE NUM, ALWAYS 0
	LD	C,$00			; C := DEVICE TYPE, 0x00 IS RS-232
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,(IY+DLPSER_CFG_DATA)	; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
; TEST FOR HARDWARE PRESENCE.
; THIS DEVICE IS VERY HARD TO DETECT.  WE USE THE PRESENCE OF
; THE STATUS PORT.  RETURN DEVICE TYPE.
;
DLPSER_DETECT:
	LD	A,(IY+DLPSER_CFG_STAT)	; STATUS PORT
	LD	C,A			; COPY TO C
	LD	($+4),A			; MODIFY CODE
DLPSER_DETECT1
	IN	A,($FF)			; READ PORT DIRECT
	IN	B,(C)			; READ PORT VIA C
	CP	B			; A==B MEANS PORT EXISTS
	LD	A,DLPSER_NONE		; ASSUME NOTHING THERE
	RET	NZ			; IF NZ, NOTHING
	LD	A,DLPSER_DLP		; ELSE TYPE IS DLP
	RET
;
;
;
DLPSER_PRTCFG:
	; ANNOUNCE PORT
	CALL	NEWLINE			; FORMATTING
	PRTS("DLPSER$")			; FORMATTING
	LD	A,(IY+CFG_DEVNUM)	; DEVICE NUM
	CALL	PRTDECB			; PRINT DEVICE NUM
	PRTS(": IO=0x$")		; FORMATTING
	LD	A,(IY+DLPSER_CFG_DATA)	; GET DATA PORT
	CALL	PRTHEXBYTE		; PRINT DATA PORT
;
	; PRINT THE DLPSER TYPE
	CALL	PC_SPACE		; FORMATTING
	LD	A,(IY+DLPSER_CFG_TYPE)	; GET DLPSER TYPE BYTE
	RLCA				; MAKE IT A WORD OFFSET
	LD	HL,DLPSER_TYPE_MAP	; POINT HL TO TYPE MAP TABLE
	CALL	ADDHLA			; HL := ENTRY
	LD	E,(HL)			; DEREFERENCE
	INC	HL			; ...
	LD	D,(HL)			; ... TO GET STRING POINTER
	CALL	WRITESTR		; PRINT IT
;
	XOR	A
	RET
;
;
;
DLPSER_TYPE_MAP:
	.DW	DLPSER_STR_NONE
	.DW	DLPSER_STR_DLP

DLPSER_STR_TAG	.TEXT	"DLPSER$"
DLPSER_STR_NONE	.DB	"<NOT PRESENT>$"
DLPSER_STR_DLP	.DB	"DLP-USB$"
;
; UART PORT TABLE
;
DLPSER_CFG:
;
DLPSER0_CFG:
	.DW	DLPSER_FNTBL			; DRIVER FUNCTION TABLE ADDRESS
	.DB	'C'				; DRIVER TYPE
	.DB	$FF				; HBIOS UNIT NUMBER (FILLED DYNAMICALLY, $FF=NONE)
	.DB	0				; DRIVER UNIT NUMBER (SET DURING INIT)
	.DB	ERR_NONE			; DEVICE STATUS (HBIOS STATUS)
	.DW	DLPSER_STR_TAG			; DRIVER TAG STRING PTR
	.DB	DLPSER_NONE			; DLPSER TYPE (SET DURING INIT)
	.DB	DLPSER0STAT			; STATUS PORT
	.DB	DLPSER0DATA			; DATA PORT
;
	DEVECHO	"DLPSER: IO="
	DEVECHO	DLPSER0DATA
	DEVECHO	"\n"
;
;
#IF (DLPSERCNT >= 2)
DLPSER1_CFG:
	.DW	DLPSER_FNTBL			; DRIVER FUNCTION TABLE ADDRESS
	.DB	'C'				; DRIVER TYPE
	.DB	$FF				; HBIOS UNIT NUMBER (FILLED DYNAMICALLY, $FF=NONE)
	.DB	0				; DRIVER UNIT NUMBER (SET DURING INIT)
	.DB	ERR_NONE			; DEVICE STATUS (HBIOS STATUS)
	.DW	DLPSER_STR_TAG			; DRIVER TAG STRING PTR
	.DB	DLPSER_NONE			; DLPSER TYPE (SET DURING INIT)
	.DB	DLPSER1STAT			; STATUS PORT
	.DB	DLPSER1DATA			; DATA PORT
;
	DEVECHO	"DLPSER: IO="
	DEVECHO	DLPSER1DATA
	DEVECHO	"\n"
#ENDIF
;
DLPSER_CFGCNT	.EQU	($ - DLPSER_CFG) / DLPSER_CFGSIZ
;
#IF (($ - DLPSER_CFG) != (DLPSER_CFGCNT * DLPSER_CFGSIZ))
	.ECHO	"*** INVALID DLPSER CONFIG TABLE ***\n"
	!!!!!
#ENDIF
;
; WORKING VARIABLES
;
DLPSER_DEV		.DB	0		; DEVICE NUM USED DURING INIT
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_DLPSER	.EQU	$
SIZ_DLPSER	.EQU	END_DLPSER - ORG_DLPSER
;	
	MEMECHO	"DLPSER occupies "
	MEMECHO	SIZ_DLPSER
	MEMECHO	" bytes.\n"
