;==================================================================================================
; DS1307 I2C CLOCK DRIVER
;
; LABELS STARTING WITH I2C ARE REFERENCING THE I2C LIBRARY (I2CPCF OR I2CBIT)
;
;==================================================================================================
;
#IF (!(I2CPCFENABLE | I2CBITENABLE))
	.ECHO	"*** DS7 DRIVER REQUIRES I2CPCFENABLE OR I2CBITENABLE!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
DS7_OUT		.EQU	10000000B		; SELECT SQUARE WAVE FUNCTION
DS7_SQWE	.EQU	00010000B		; ENABLE SQUARE WAVE OUTPUT
DS7_RATE	.EQU	00000000B		; SET 1HZ OUPUT
;
;DS7_DS1307    	.EQU  	11010000B   		; DEVICE IDENTIFIER
DS7_DS1307    	.EQU  	68H	   		; DEVICE IDENTIFIER
DS7_W   	.EQU  	00000000B   		; DEVICE WRITE
DS7_R   	.EQU  	00000001B   		; DEVICE READ
;
DS7_READ   	.EQU    (DS7_DS1307 << 1 | DS7_R)	; READ
DS7_WRITE 	.EQU    (DS7_DS1307 << 1 | DS7_W)	; WRITE
;
DS7_CTL		.EQU	(DS7_OUT | DS7_SQWE | DS7_RATE)
;
		DEVECHO	"DS1307: I2C ADDR="
		DEVECHO	DS7_DS1307
		DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_DS7	.EQU	$
;
	.DW	SIZ_DS7		; MODULE SIZE
	.DW	DS7_INITPHASE		; ADR OF INIT PHASE HANDLER
;
DS7_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	;CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	;JP	Z,DS7RTC_PREINIT	; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,DS7RTC_INIT		; DO INIT
	RET				; DONE
;
;-----------------------------------------------------------------------------
; DS1307 INITIALIZATION
;
; ASSUMES I2C HAS ALREADY BEEN INITIALIZED
; CHECKS IF OSCILLATOR IS RUNNING. IF IT ISN'T THE
; CLOCK IS RESTARTED WITH DEFAULT VALUES.
;
; DRIVER WILL NOT BE INSTALLED AS PART OF HBIOS IF
; THERE IS ALREADY AN EXISTING RTC INSTALLED.
;
; 12HR MODE IS CURRENTLY ASSUMED
;
DS7RTC_INIT:
	CALL	NEWLINE			; FORMATTING
	PRTS("DS1307: $")		; ANNOUNCE DRIVER
;
	PRTS("I2C ADDR=0x$")
	LD	A,DS7_DS1307
	CALL	PRTHEXBYTE
	CALL	PC_SPACE
;
	LD	A,(I2C_FAIL_FLAG)	; CHECK IF THE
	OR	A			; I2C DRIVER
	JR	NZ,RTC_INIT_FAIL	; INITIALIZED

	CALL	DS7_RDC			; READ CLOCK DATA
	JR	NZ,DS7_INIT_NOACK	; DS1307 DIDN'T RESPOND
	LD	HL,DS7_BUF		; IF NOT RUNNING OR
	BIT	7,(HL)			; INVALID, RESTART
	JR	Z,DS7_CSET		; AND RESET.
	CALL	DS7_SETC
	CALL	DS7_RDC			; READ AND DISPLAY
	JR	NZ,DS7_INIT_NOACK	; DS1307 STOPPED RESPONDING
DS7_CSET:
	CALL	DS7_DISP		; DATE AND TIME
;
	LD	A,(RTC_DISPACT)		; CHECK RTC DISPATCHER STATUS.
	OR	A			; RETURN NOW IF WE ALREADY HAVE
	RET	NZ			; A PRIMARY RTC INSTALLED.
;
	LD	BC,DS7_DISPATCH		; SETUP CLOCK HBIOS DISATCHER
	CALL	RTC_SETDISP
;
;	CALL	DS7_GETTIM
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
; I2C IS FINE, DS1307 ITSELF DIDN'T ACK
;
DS7_INIT_NOACK:			; EXIT
	PRTS("NOT PRESENT$")		; WITH ERROR
	PUSH	AF
	JR	RTC_INIT_ERR
;
RTC_INIT_FAIL:				; EXIT
	PRTS("I2C FAILURE$")		; WITH ERROR MESSAGE
	PUSH	AF
RTC_INIT_ERR:				; EXIT
	POP	AF			; WITH
	LD	A,ERR_NOHW		; ERROR
	OR	A			; STATUS
	RET
;
;-----------------------------------------------------------------------------
; DS1307 HBIOS DISPATCHER
;
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERROR
;   B: FUNCTION (IN)
;
DS7_DISPATCH:
	PUSH	AF				; CHECK IF WE
	LD	A,(I2C_FAIL_FLAG)		; HAVE HARDWARE
	OR	A				; AND ASSOCIATED
	JR	NZ,RTC_INIT_ERR			; DRIVER
	POP	AF
;
	LD	A, B				; GET REQUESTED FUNCTION
	AND	$0F				; ISOLATE SUB-FUNCTION
	JP	Z, DS7_GETTIM			; GET TIME
	DEC	A
	JP	Z, DS7_SETTIM			; SET TIME 
	DEC	A
	JP	Z, DS7_GETBYT			; GET NVRAM BYTE VALUE
	DEC	A
	JP	Z, DS7_SETBYT			; SET NVRAM BYTE VALUE
	DEC	A
	JP	Z, DS7_GETBLK			; GET NVRAM DATA BLOCK VALUE
	DEC	A
	JP	Z, DS7_SETBLK			; SET NVRAM DATA BLOCK VALUE 
	DEC	A
	JP	Z, DS7_GETALM			; GET ALARM
	DEC	A
	JP	Z, DS7_SETALM			; SET ALARM
	DEC	A
	JP	Z, DS7_DEVICE			; REPORT RTC DEVICE INFO
	SYSCHKERR(ERR_NOFUNC)
	RET
;
;-----------------------------------------------------------------------------
; DS1307 GET TIME
;
; HL POINTS TO A BUFFER TO STORE THE CURRENT TIME AND DATE IN.
; THE TIME AND DATE INFORMATION MUST BE TRANSLATED TO THE
; HBIOS FORMAT AND COPIED FROM THE HBIOS DRIVER BANK TO
; CALLER INVOKED BANK.
;
; HBIOS FORMAT  = YYMMDDHHMMSS
; DS1307 FORMAT = SSMMHH..DDMMYY..
;
DS7_GETTIM:
	PUSH	HL				; SAVE DESTINATION
	CALL	DS7_RDC				; READ THE CLOCK INTO THE BUFFER
	JR	NZ,DS7_GETTIM_ERR		; BAIL IF READ FAILED, BUFFER IS GARBAGE
;
	LD	HL,DS7_BUF+2
	LD	DE,DS7_BUF+3			; TRANSLATE
	LD	B,3				; FORMAT
DS7_GT0:LD	A,(HL)
	LD	(DE),A	
	INC	DE
	LD	A,(DE)
	LD	(HL),A
	DEC	HL
	DJNZ	DS7_GT0
;
	INC	HL				; POINT TO SECONDS
	RES	7,(HL)				; REMOVE OSCILLATOR BIT
	POP	DE				; HL POINT TO SOURCE
;						; DE POINT TO DESTINATION
#IF (0)
	PUSH	HL
	PUSH	DE
	EX	DE,HL
	LD	A,6
	CALL	PRTHEXBUF
	POP	DE
	POP	HL
#ENDIF
;	
	LD	A,BID_BIOS			; COPY FROM BIOS BANK
	LD	(HB_SRCBNK),A			; SET IT 
	LD	A, (HB_INVBNK)			; COPY TO CURRENT USER BANK
	LD	(HB_DSTBNK),A			; SET IT
	LD	BC, 6				; LENGTH IS 6 BYTES
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY			; COPY THE CLOCK DATA
#IF (INTMODE == 1)
	EI
#ENDIF
	XOR	A				; SIGNAL SUCCESS
	RET
;
DS7_GETTIM_ERR:
	POP	HL				; DISCARD SAVED DESTINATION, NOT WRITING TO IT
	RET					; NZ ALREADY SET BY DS7_RDC
;
;-----------------------------------------------------------------------------
; DS1307 SET TIME
;
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERROR
;   HL: DATE/TIME BUFFER (IN)
;
; HBIOS FORMAT  = YYMMDDHHMMSS
; DS1307 FORMAT = SSMMHH..DDMMYY..
;
DS7_SETTIM:
;	CALL	PCF_DBG		; [0]


	LD	A, (HB_INVBNK)			; COPY FROM CURRENT USER BANK
	LD	(HB_SRCBNK), A			; SET IT
	LD	A, BID_BIOS			; COPY TO BIOS BANK
	LD	(HB_DSTBNK), A			; SET IT
	LD	DE, DS7_BUF			; DESTINATION ADDRESS
	LD	BC,6				; LENGTH IS 6 BYTES
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY			; Copy the clock data
#IF (INTMODE == 1)
	EI
#ENDIF
;
;	CALL	PCF_DBG		; [1]

	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;	
	LD	A,DS7_WRITE	; SET SLAVE ADDRESS
        CALL	I2C_START_ADDR	; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN; AND ISSUE THE SLAVE ADDRESS
	CALL	NZ,I2C_PINERR
;
	LD	A,00H		; REGISTER 00
        CALL	I2C_PUTBYTE_PIN	; PUT ADDRESS ON BUS
	CALL	NZ,I2C_PINERR
;
	LD	DE,5
	CALL	DS7_SET3	; STARTING AT REGISTER 0
;
	CALL 	I2C_STOP

	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR

;	CALL	PCF_DBG		; [2]
;
	LD	A,DS7_WRITE	; SET SLAVE ADDRESS
        CALL	I2C_START_ADDR	; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN; AND ISSUE THE SLAVE ADDRESS
	CALL	NZ,I2C_PINERR

;	CALL	PCF_DBG		; [3]
;
	LD	A,04H		; REGISTER 04
        CALL	I2C_PUTBYTE_PIN	; PUT ADDRESS ON BUS
	CALL	NZ,I2C_PINERR
;
	LD	DE,2
	CALL	DS7_SET3
	; I2C_STOP CLOBBERS A, NOT FLAGS
	PUSH	AF		; SAVE RESULT

;	CALL	PCF_DBG		; [4]
;
	CALL 	I2C_STOP
	POP	AF		; RESTORE DS7_SET3'S REAL RESULT
	RET
;
DS7_SET3:
	LD	B,3
	LD	HL,DS7_BUF
	ADD	HL,DE
DS7_SC1:PUSH	BC

	LD	A,(HL)

;	CALL	PRTHEXBYTE

        CALL	I2C_PUTBYTE_ACK	; PUT DATA ON BUS
	CALL	NZ,I2C_ACKERR
	POP	BC
	DEC	HL
	DJNZ	DS7_SC1
	RET
;
; HBIOS FORMAT  = YYMMDDHHMMSS
;                 991122083100
; DS1307 FORMAT = SSMMHH..DDMMYY..
;                 003108..221199
;
;-----------------------------------------------------------------------------
; DS1307 NVRAM: 56 BYTES AT REGISTERS 08H-3FH. INDEX (C) MAPS TO 08H+INDEX.
;
DS7_NVBASE	.EQU	08H
;
; GET NVRAM BYTE
;   C: INDEX
;   E: VALUE (OUTPUT)
;
DS7_GETBYT:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS7_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,C
	ADD	A,DS7_NVBASE
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	CALL	I2C_REPSTART
;
	LD	A,DS7_READ
	CALL	I2C_PUTBYTE
	CALL	I2C_READI2C	; DUMMY READ, PCF8584 QUIRK -- REAL DATA STARTS NEXT
;
	CALL	I2C_PREPNACK	; SINGLE BYTE, NACK IT NOW
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
	CALL	I2C_GETBYTE
	LD	E,A
;
	JP	DS7_WTPIN
;
; SET NVRAM BYTE
;   C: INDEX
;   E: VALUE
;
DS7_SETBYT:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS7_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,C
	ADD	A,DS7_NVBASE
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,E
	CALL	I2C_PUTBYTE_ACK
	CALL	NZ,I2C_ACKERR
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; FUNCTIONS THAT ARE NOT AVAILABLE OR IMPLEMENTED
;
DS7_GETBLK:
DS7_SETBLK:
DS7_SETALM
DS7_GETALM
	SYSCHKERR(ERR_NOTIMPL)
	RET
;-----------------------------------------------------------------------------
; REPORT RTC DEVICE INFO
;
; THE I2C BUS ADDRESS IS REPORTED RATHER THAN THE I2C PORT ADDRESS.
; ONLY ONE CLOCK CAN BE INSTALLED IN HBIOS SO DEVICE NUMBER IS ALWAYS 0.
;
DS7_DEVICE:
	LD	D,RTCDEV_DS7		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL DEVICE NUMBER
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,DS7_DS1307		; L := BUS ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;-----------------------------------------------------------------------------
; RTC READ
;
; 1.	ISSUE SLAVE ADDRESS WITH START CONDITION AND WRITE STATUS
; 2.	OUTPUT THE ADDRESS TO ACCESS. (00H = START OF DS1307 REGISTERS)
; 3.	OUTPUT REPEAT START TO TRANSITION TO READ PROCESS
; 4.	ISSUE SLAVE ADDRESS WITH READ STATUS
; 5. 	DO A DUMMY READ 
; 6.	READ 8 BYTES STARTING AT ADDRESS PREVIOUSLY SET
; 7.	END READ WITH NON-ACKNOWLEDGE
; 8.	ISSUE STOP AND RELEASE BUS 
;
DS7_RDC:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS7_WRITE	; SET SLAVE ADDRESS
        CALL	I2C_START_ADDR	; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN; AND ISSUE THE SLAVE ADDRESS
	JR	Z,DS7_RDC_ADDROK
;
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET
;
DS7_RDC_ADDROK:
        LD     	A,0
        CALL	I2C_PUTBYTE_PIN	; PUT ADDRESS MSB ON BUS
	CALL	NZ,I2C_PINERR
;
	CALL	I2C_REPSTART    ; REPEAT START
;
        LD	A,DS7_READ	; ISSUE CONTROL BYTE + READ
        CALL	I2C_PUTBYTE
;
	CALL	I2C_READI2C	; DUMMY READ
;
	LD	HL,DS7_BUF	; READ FIRST 7 BYTES NORMALLY (ACK'D)
	LD	B,7
DS7_RL1:CALL	I2C_READI2C
	LD	(HL),A
	INC	HL
	DJNZ    DS7_RL1
;
	CALL	I2C_PREPNACK	; PREP NEGATIVE ACK FOR THE 8TH (LAST) BYTE
	CALL	I2C_WAIT_FOR_PIN; WAIT FOR IT -- NOT I2C_READI2C, ITS LRB
	CALL	NZ,I2C_PINERR	; CHECK WOULD MISFIRE ON OUR OWN NACK
	CALL	I2C_GETBYTE	; READ THE FINAL BYTE, NACK ALREADY SENT
	LD	(HL),A
;
#IF (0)
	LD	A,8
	LD	DE,DS7_BUF	; DISPLAY DATA READ
	CALL	PRTHEXBUF	;
	CALL   	NEWLINE
#ENDIF
;
; RETURNS Z/A=00 IF PIN CLEARED
; NZ/A=FF ON TIMEOUT
; NZ/A=01 ON LOST ARBITRATION
;
DS7_WTPIN:
	CALL	I2C_WAIT_FOR_PIN
	PUSH	AF		; SAVE RESULT -- I2C_STOP CLOBBERS A
	CALL	I2C_STOP
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; SET CLOCK
;
; IF THE CLOCK IS HALTED AS IDENTIFIED BY BIT 7 REGISTER 0, THEN ASSUME THE
; CLOCK HAS NOT BEEN SET AND SO SET THE CLOCK UP WITH A DEFAULT SET OF
; VALUES AS DEFINED IN THE DS7_CLKDATA TABLE.
;
DS7_SETC:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;	
	LD	A,DS7_WRITE	; SET SLAVE ADDRESS
        CALL	I2C_START_ADDR	; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN; AND ISSUE THE SLAVE ADDRESS
	CALL	NZ,I2C_PINERR
;
	LD	A,00H		; REGISTER 00
        CALL	I2C_PUTBYTE_PIN	; PUT ADDRESS ON BUS
	CALL	NZ,I2C_PINERR
;
	LD	C,0		; ACCUMULATE WRITE FAILURES
	LD	DE,DS7_CLKDATA
DS7_SC:	LD	A,(DE)
	CP	0FFH
	JR	Z,DS7_ESC
        CALL	I2C_PUTBYTE_ACK	; PUT DATA ON BUS
	JR	Z,DS7_SCC1
	INC	C		; REMEMBER FAILURE
	CALL	I2C_ACKERR
DS7_SCC1:
	INC	DE
	JR	DS7_SC
;
DS7_ESC:CALL 	I2C_STOP
	LD	A,C
	OR	A		; SET Z/NZ FOR CALLER
	RET
;
DS7_CLKDATA:
	.DB	00H		; SECONDS
	.DB	00H		; MINUTES
	.DB     00H		; HOURS
	.DB	01H		; DAY
	.DB	01H		; DATE
	.DB	01H		; MONTH
	.DB	21H		; YEAR
        .DB     DS7_CTL		; CONTROL (00010011B)
        .DB     0FFH            ; END FLAG  
;
;-----------------------------------------------------------------------------
; DISPLAY CLOCK INFORMATION FROM DATA STORED IN BUFFER
;
DS7_DISP:
	LD	HL,DS7_CLKTBL
DS7_CLP:LD	C,(HL)
	INC	HL
	LD	D,(HL)
	CALL	DS7_BCD
	INC	HL
	LD	A,(HL)
	OR      A
	RET	Z
        CALL	COUT
	INC	HL
	JR	DS7_CLP
	RET
;
DS7_CLKTBL:
	.DB	04H, 00111111B, '/'	; DD: 31
	.DB	05H, 00011111B, '/'	; MM: 12
	.DB	06H, 11111111B, ' '	; YY: 99
	.DB	02H, 01111111B, ':'	; SS: 59
	.DB	01H, 01111111B, ':'	; MM: 59
	.DB	00H, 00111111B, 00H	; HH: 24
;
DS7_BCD:PUSH	HL
	LD      HL,DS7_BUF     	; READ VALUE FROM
	LD      B,0           	; BUFFER, INDEXED BY A 
	ADD     HL,BC
	LD      A,(HL)
	AND     D             	; MASK OFF UNNEEDED
	SRL     A
	SRL     A
	SRL     A
	SRL     A      
	ADD     A,30H
	CALL    COUT
	LD      A,(HL)    
	AND     00001111B
	ADD     A,30H
	CALL    COUT
	POP	HL
	RET
;
DS7_BUF:	.FILL	8,0				; BUFFER FOR TIME, DATE AND CONTROL
;DS7_COLD	.DB	$80,$00,$00,$01,$01,$01,$00	; COLD START RTC SETTINGS
;
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_DS7	.EQU	$
SIZ_DS7	.EQU	END_DS7 - ORG_DS7
;	
	MEMECHO	"DS7 occupies "
	MEMECHO	SIZ_DS7
	MEMECHO	" bytes.\n"
