;
;==================================================================================================
;   RAM FLOPPY DISK DRIVER
;==================================================================================================
;
;
;
RF_U0IO		.EQU	$A0		; BASED ADDRESS OF RAMFLOPPY 1
RF_U1IO		.EQU	$A4		; BASED ADDRESS OF RAMFLOPPY 2
RF_U2IO		.EQU	$A8		; BASED ADDRESS OF RAMFLOPPY 3
RF_U3IO		.EQU	$AC		; BASED ADDRESS OF RAMFLOPPY 4
;
; IO PORT OFFSETS
;
RF_DAT		.EQU	0		; DATA IN/OUT ONLY TO SRAM      - R/W
RF_AL		.EQU	1		; ADDRESS LOW FOR RAMF MEMORY   - W/O
RF_AH		.EQU	2		; ADDRESS HIGH FOR RAMF MEMORY  - W/O
RF_ST		.EQU	3		; STATUS PORT			- R/O
;
; RF DEVICE CONFIGURATION
;
; PER DEVICE DATA OFFSETS IN CFG BLOCK
; BYTES 0-15 ARE STANDARD (SEE STD.ASM DRIVER CONFIG BLOCK STANDARD OFFSETS)
;
RF_CFG_IOBASE	.EQU	16		; IO BASE ADDRESS (BYTE)
;
RF_CFGSIZ	.EQU	17		; SIZE OF CFG TBL ENTRIES
;
RF_DEVCNT	.EQU	RFCNT		; NUMBER OF RF DEVICES SUPPORTED
RF_MAXRF	.EQU	4		; MAXIMUM NUMBERS OF DEVICES SUPPORTED
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_RF	.EQU	$
;
	.DW	SIZ_RF			; MODULE SIZE
	.DW	RF_INITPHASE		; ADR OF INIT PHASE HANDLER
;
RF_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	;CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	;JP	Z,RF_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,RF_INIT		; DO INIT
	RET				; DONE

#IF (RF_DEVCNT > RF_MAXRF)
	.ECHO	"*** ONLY 4 RAM FLOPPY DEVICES SUPPORTED ***\n"
RF_DEVCNT	.SET	RF_MAXRF
#ENDIF
;
; RF DEVICE CONFIG BLOCKS
;
; NOTE THAT DISK CAPACITY IS HARD CODED HERE TO 4MB:
;   - CAPACITY = 8192 BLOCKS OF 512 BYTES = $2000 BLOCKS
;
RF_CFGTBL:
;
#IF (RF_DEVCNT >= 1)
RF0_CFG:	; DEVICE 0
	.DW	RF_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	0			; DRIVER UNIT NUMBER
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	RF_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	$2000,0			; DEVICE CAPACITY = $2000 BLOCKS, LSW:MSW
	.DB	RF_U0IO			; IO BASE ADDRESS
;
	DEVECHO	"RF: IO="
	DEVECHO	RF_U0IO
	DEVECHO	"\n"
#ENDIF
;
#IF (RF_DEVCNT >= 2)
RF1_CFG:	; DEVICE 1
	.DW	RF_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	1			; DRIVER UNIT NUMBER
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	RF_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	$2000,0			; DEVICE CAPACITY = $2000 BLOCKS, LSW:MSW
	.DB	RF_U1IO			; IO BASE ADDRESS
;
	DEVECHO	"RF: IO="
	DEVECHO	RF_U1IO
	DEVECHO	"\n"
#ENDIF
;
#IF (RF_DEVCNT >= 3)
RF2_CFG:	; DEVICE 2
	.DW	RF_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	2			; DRIVER UNIT NUMBER
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	RF_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	$2000,0			; DEVICE CAPACITY = $2000 BLOCKS, LSW:MSW
	.DB	RF_U2IO			; IO BASE ADDRESS
;
	DEVECHO	"RF: IO="
	DEVECHO	RF_U2IO
	DEVECHO	"\n"
#ENDIF
;
#IF (RF_DEVCNT >= 4)
RF3_CFG:	; DEVICE 3
	.DW	RF_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	3			; DRIVER UNIT NUMBER
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	RF_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	$2000,0			; DEVICE CAPACITY = $2000 BLOCKS, LSW:MSW
	.DB	RF_U3IO			; IO BASE ADDRESS
;
	DEVECHO	"RF: IO="
	DEVECHO	RF_U3IO
	DEVECHO	"\n"
#ENDIF
;
#IF ($ - RF_CFGTBL) != (RF_DEVCNT * RF_CFGSIZ)
	.ECHO	"*** INVALID RF CONFIG TABLE ***\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
;=============================================================================
; INITIALIZATION ENTRY POINT
;=============================================================================
;
RF_INIT:
	; LOOP THRU CONFIG TABLE BY DEVICE COUNT
	LD	IY,RF_CFGTBL		; POINT TO START OF CONFIG TABLE
	LD	B,RF_DEVCNT		; DEVICE COUNT
	LD	A,B			; TEST FOR
	OR	A			; ... ZERO DEVICES
	RET	Z			; NOTHING TO DO
;
RF_INIT1:
	PUSH	BC			; SAVE LOOP COUNTER
	CALL	RF_INIT2		; REGISTER & INIT DEVICE
	POP	BC			; RESTORE LOOP COUNTER
	LD	DE,RF_CFGSIZ		; SIZE OF CFG TABLE ENTRY
	ADD	IY,DE			; BUMP POINTER
	DJNZ	RF_INIT1		; LOOP AS NEEDED
;
	XOR	A			; SUCCESS
	RET				; DONE
;
RF_INIT2:
	; ADD UNIT TO GLOBAL DISK UNIT TABLE
	LD	BC,RF_FNTBL		; BC := FUNC TABLE ADR
	PUSH	IY			; CFG ENTRY POINTER
	POP	DE			; COPY TO DE
	CALL	DIO_ADDENT		; ADD ENTRY TO GLOBAL DISK DEV TABLE
	LD	(IY+CFG_UNIT),A		; RECORD HBIOS UNIT NUMBER ASSIGNED
;
	CALL	RF_INITDEV		; INITIALIZE DEVICE
	PUSH	AF			; SAVE INIT STATUS
;
	CALL	DRV_PRTTAG		; TAG FOR ACTIVE DEVICE
	PRTS(" IO=0x$")			; LABEL FOR IO ADDRESS
	LD	A,(IY+RF_CFG_IOBASE)	; GET IO BASE ADDRES
	CALL	PRTHEXBYTE		; DISPLAY IT
;
	PRTS(" WP=$")			; LABEL FOR WRITE PROTECT
	CALL	RF_CHKWP		; NZ=WRITE PROTECTED
	LD	DE,RF_STR_ON		; ASSUME ON
	JR	NZ,RF_INIT2A		; IF NZ, IT IS ON
	LD	DE,RF_STR_OFF		; ELSE OFF
RF_INIT2A:
	CALL	WRITESTR		; PRINT IT
;
	POP	AF			; RECOVER INIT STATUS
	JR	Z,RF_INIT3		; IF Z, CONTINUE
	JP	ERR_PRT_SP		; ELSE ERROR TEXT AND ABORT
;
RF_INIT3:
	; PRINT STORAGE CAPACITY (BLOCK COUNT)
	PRTS(" BLOCKS=0x$")		; PRINT FIELD LABEL
	LD	A,CFG_DSKCAP		; OFFSET TO CAPACITY FIELD
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	LD32			; GET THE CAPACITY VALUE
	CALL	PRTHEX32		; PRINT HEX VALUE
;
	; PRINT STORAGE SIZE IN MB
	PRTS(" SIZE=$")			; PRINT FIELD LABEL
	LD	B,11			; 11 BIT SHIFT TO CONVERT BLOCKS --> MB
	CALL	SRL32			; RIGHT SHIFT
	CALL	PRTDEC32		; PRINT DWORD IN DECIMAL
	PRTS("MB$")			; PRINT SUFFIX
;
	XOR	A			; SUCCESS
	RET
;
;=============================================================================
; DRIVER FUNCTION TABLE
;=============================================================================
;
RF_FNTBL:
	.DW	RF_STATUS
	.DW	RF_RESET
	.DW	RF_SEEK
	.DW	RF_READ
	.DW	RF_WRITE
	.DW	RF_VERIFY
	.DW	RF_FORMAT
	.DW	RF_DEVICE
	.DW	RF_MEDIA
	.DW	RF_DEFMED
	.DW	RF_CAP
	.DW	RF_GEOM
#IF (($ - RF_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID RF FUNCTION TABLE ***\n"
#ENDIF
;
RF_VERIFY:
RF_FORMAT:
RF_DEFMED:
	SYSCHKERR(ERR_NOTIMPL)		; NOT IMPLEMENTED
	RET
;
;
;
RF_READ:
	CALL	HB_DSKREAD		; HOOK HBIOS DISK READ SUPERVISOR
	LD	BC,RF_RDSEC		; SECTOR READ FUNC
	JP	RF_IO			; DO THE IO
;
;
;
RF_WRITE:
	; CHECK WRITE PROTECT BEFORE HOOKING THE SUPERVISOR SO THAT
	; WE RETURN ZERO SECTORS WRITTEN AND DON'T FLAG A DEVICE ERROR.
	PUSH	BC			; SAVE HBIOS FUNC & UNIT
	CALL	RF_CHKWP		; WRITE PROTECTED?
	POP	BC			; RESTORE HBIOS FUNC & UNIT
	JR	NZ,RF_WRITE_RO		; IF SO, HANDLE READ ONLY
;
	CALL	HB_DSKWRITE		; HOOK HBIOS DISK WRITE SUPERVISOR
	LD	BC,RF_WRSEC		; SECTOR WRITE FUNC
	JP	RF_IO			; DO THE IO
;
RF_WRITE_RO:
	LD	E,0			; ZERO SECTORS WRITTEN
	LD	A,ERR_READONLY		; SIGNAL ERROR
	OR	A			; SET FLAGS
	RET				; AND DONE
;
;
;
RF_STATUS:
	LD	A,(IY+CFG_STATUS)	; GET STATUS OF SELECTED DEVICE
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
;
;
RF_RESET:
	JP	RF_INITDEV		; REINITIALIZE UNIT AND RETURN
;
;
;
RF_DEVICE:
	LD	D,DIODEV_RF		; D := DEVICE TYPE
	LD	E,(IY+CFG_DEVNUM)	; E := PHYSICAL DEVICE NUMBER
	LD	C,%00010111		; C := ATTRIBUTES, NON-REMOVABLE RAM FLOPPY
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,(IY+RF_CFG_IOBASE)	; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
;
;
RF_MEDIA:
	; CHECK IF MEDIA DISCOVERY REQUESTED
	BIT	0,E			; IF BIT 0 OF E, CHECK MEDIA
	LD	D,0			; SIGNAL NO MEDIA CHANGE
	JR	Z,RF_MEDIA_Z		; IF NOT SET, REPORT CURRENT INFO
;
	; CHECK CURRENT DEVICE STATUS
	LD	A,(IY+CFG_STATUS)	; GET OUR CURRENT STATUS
	OR	A			; SET FLAGS
	JR	Z,RF_MEDIA_Z		; IF OK, NOTHING MORE TO CHECK FOR RAM FLOPPY
;
	; ATTEMPT TO RECOVER FROM ERROR STATE USING INITDEV
	; CURRENT STATUS WILL BE SET/CLEARED BY INITDEV
	CALL	RF_INITDEV		; PERFORM INIT
	LD	D,1			; SIGNAL MEDIA CHANGE
	; AND FALL THRU
;
RF_MEDIA_Z:
	LD	A,(IY+CFG_STATUS)	; GET CURRENT STATUS
	OR	A			; SET FLAGS
	LD	E,MID_RF		; ASSUME RAM FLOPPY MEDIA
	RET	Z			; RETURN IF GOOD
	LD	E,MID_NONE		; ELSE SIGNAL NO MEDIA
	RET				; AND RETURN ERROR
;
;
;
RF_SEEK:
	JP	HB_DSKSEEKLBA		; USE GENERIC LBA SEEK ROUTINE
;
; GET DISK CAPACITY
;
RF_CAP:
	JP	HB_DSKCAP		; USE GENERIC CAPACITY ROUTINE
;
; GET DISK GEOMETRY
;
RF_GEOM:
	JP	HB_DSKGEOMLBA		; USE GENERIC LBA GEOMETRY ROUTINE
;
;=============================================================================
; FUNCTION SUPPORT ROUTINES
;=============================================================================
;
; INITIALIZE OR REINITIALIZE DEVICE
; RETURN HBIOS RESULT CODE
;
; THE RAM FLOPPY HAS NOTHING TO RESET, SO JUST MARK THE DEVICE READY.
; CFG_DSKADR IS NOT TOUCHED SINCE A RESET MAY OCCUR BETWEEN A SEEK
; AND THE SUBSEQUENT I/O.
;
RF_INITDEV:
	XOR	A			; STATUS := OK
	LD	(IY+CFG_STATUS),A	; SAVE IT
	RET				; DONE, A=0, ZF SET
;
; PERFORM SECTOR READ/WRITE
; ON ENTRY, BC=SECTOR READ/WRITE FUNCTION, HL=DATA BUFFER
; RETURN HBIOS RESULT CODE
;
RF_IO:
	LD	(RF_DSKBUF),HL		; SAVE DISK BUFFER ADDRESS
	LD	H,B			; SECTOR FUNC
	LD	L,C			; ... TO HL
	CALL	JPHL			; DO THE SECTOR READ/WRITE
	JP	NZ,RF_ERR		; HANDLE ERROR AND RETURN
;
	CALL	HB_DSKINCLBA		; INCREMENT LBA
;
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
; HANDLE AN I/O ERROR.  THE ONLY POSSIBLE RF SECTOR ERROR IS A DMA
; TRANSFER FAILURE, WHICH IS MAPPED TO HBIOS IO ERROR.  THE ERROR IS
; RECORDED AS THE PERSISTENT DEVICE STATUS, SO THE NEXT I/O WILL
; REINITIALIZE THE DEVICE VIA THE DISK SUPERVISOR.
;
RF_ERR:
	LD	A,ERR_IO		; HBIOS ERR TO ACCUM
	LD	(IY+CFG_STATUS),A	; SET PERSISTENT STATUS
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
;=============================================================================
; HARDWARE INTERFACE ROUTINES
;=============================================================================
;
; READ SECTOR
;
RF_RDSEC:
	CALL	RF_SETADR		; SEND SECTOR STARTING ADDRESS TO CARD
	LD	HL,(RF_DSKBUF)		; HL := DISK BUFFER ADDRESS
	LD	A,(IY+RF_CFG_IOBASE)	; GET IO PORT BASE
	OR	RF_DAT			; OFFSET TO DAT PORT
#IF (DMAENABLE & (DMAMODE=DMAMODE_ECB))
	LD	BC,512-1		; READ 512 BYTES
	CALL	DMAINIR			; USING DMA
#ELSE
	LD	C,A			; PUT IN C FOR PORT IO
	LD	B,0			; INIT BYTE COUNTER
	INIR				; READ 256 BYTES
	INIR				; AND ANOTHER 256 BYTES FOR 512 TOTAL
	XOR	A			; SIGNAL SUCCESS
#ENDIF
	RET				; AND DONE
;
; WRITE SECTOR
;
RF_WRSEC:
	CALL	RF_SETADR		; SEND SECTOR STARTING ADDRESS TO CARD
	LD	HL,(RF_DSKBUF)		; HL := DISK BUFFER ADDRESS
	LD	A,(IY+RF_CFG_IOBASE)	; GET IO PORT BASE
	OR	RF_DAT			; OFFSET TO DAT PORT
#IF (DMAENABLE & (DMAMODE=DMAMODE_ECB))
	LD	BC,512-1		; WRITE 512 BYTES
	CALL	DMAOTIR			; USING DMA
#ELSE
	LD	C,A			; PUT IN C FOR PORT IO
	LD	B,0			; INIT BYTE COUNTER
	OTIR				; WRITE 256 BYTES
	OTIR				; AND ANOTHER 256 BYTES FOR 512 TOTAL
	XOR	A			; SIGNAL SUCCESS
#ENDIF
	RET				; AND DONE
;
; SEND LOW 16 BITS OF CURRENT LBA TO CARD AS THE SECTOR ADDRESS.
; WRITING THE ADDRESS ALSO RESETS THE CARD'S BYTE COUNTER.
;
RF_SETADR:
	LD	A,(IY+RF_CFG_IOBASE)	; GET IO PORT BASE
	OR	RF_AL			; OFFSET TO ADDRESS LOW PORT
	LD	C,A			; PUT IN C FOR PORT IO
	LD	A,(IY+CFG_DSKADR+0)	; LBA LSB
	OUT	(C),A			; TO ADDRESS LOW PORT
	LD	A,(IY+CFG_DSKADR+1)	; LBA MSB
	INC	C			; BUMP TO ADDRESS HIGH PORT
	OUT	(C),A			; SEND IT
	RET
;
; CHECK WRITE PROTECT
; RETURNS WP STATUS IN ZF, NZ=WRITE PROTECTED
; DESTROYS AF, C
;
RF_CHKWP:
	LD	A,(IY+RF_CFG_IOBASE)	; GET IO PORT BASE
	OR	RF_ST			; OFFSET TO ST PORT
	LD	C,A			; PUT PORT ADR IN C FOR IO
	IN	A,(C)			; READ ST PORT
	BIT	0,A			; CHECK WRITE PROTECT (BIT 0)
	RET				; RET WP STATUS IN ZF, NZ=WP
;
;=============================================================================
; STRING DATA
;=============================================================================
;
RF_STR_TAG	.TEXT	"RF$"
RF_STR_ON	.TEXT	"ON$"
RF_STR_OFF	.TEXT	"OFF$"
;
;==================================================================================================
;   RF DISK DRIVER - DATA
;==================================================================================================
;
RF_DSKBUF	.DW	0		; CURRENT DISK BUFFER ADDRESS
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_RF	.EQU	$
SIZ_RF	.EQU	END_RF - ORG_RF
;
	MEMECHO	"RF occupies "
	MEMECHO	SIZ_RF
	MEMECHO	" bytes.\n"
