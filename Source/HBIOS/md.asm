;
;==================================================================================================
;   MD DISK DRIVER (MEMORY DISK)
;==================================================================================================
;
; MD DEVICE CONFIGURATION
;
;
;       DISK DEVICE TYPE ID	MEDIA ID		ATTRIBUTE
;--------------------------------------------------------------------------------------------------
;	0x00 MEMORY DISK	0x02 RAM DRIVE		%00101000 HD STYLE, NON-REMOVABLE, TYPE-RAM
;	0x00 MEMORY DISK	0x01 ROM DRIVE		%00100000 HD STYLE, NON-REMOVABLE, TYPE-ROM
;	0x00 MEMORY DISK	0x01 ROM DRIVE		%00111000 HD STYLE, NON-REMOVABLE, TYPE-FLASH
;
; PER DEVICE DATA OFFSETS IN CFG BLOCK
; BYTES 0-15 ARE STANDARD (SEE STD.ASM DRIVER CONFIG BLOCK STANDARD OFFSETS)
;
MD_CFG_MID	.EQU	16		; MEDIA ID (BYTE)
MD_CFG_ATTRIB	.EQU	17		; DEVICE ATTRIBUTE (BYTE)
;
MD_CFGSIZ	.EQU	18		; SIZE OF CFG TBL ENTRIES
;
MD_AROM		.EQU	%00010100	; ROM ATTRIBUTE
MD_ARAM		.EQU	%00010101	; RAM ATTRIBUTE
MD_AFSH		.EQU	%00010110	; FLASH ATTRIBUTE
;
MD_FDBG		.EQU	0		; FLASH DEBUG CODE
MD_FVBS		.EQU	1		; FLASH VERBOSE OUTPUT
MD_FVAR		.EQU	1		; FLASH VERIFY AFTER WRITE
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MD	.EQU	$
;
	.DW	SIZ_MD			; MODULE SIZE
	.DW	MD_INITPHASE		; ADR OF INIT PHASE HANDLER
;
MD_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	;CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	;JP	Z,MD_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,MD_INIT		; DO INIT
	RET				; DONE
;
; DEVICE CONFIG TABLE (RAM DEVICE FIRST TO MAKE IT ALWAYS FIRST DRIVE)
;
MD_CFGTBL:
;
#IF (MDRAM)
MD_RAM_CFG:	; DEVICE 0 (RAM)
	.DW	MD_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	0			; DRIVER UNIT NUMBER (0=RAM)
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	MD_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	0,0			; DEVICE CAPACITY (BLOCKS, SET BY INITDEV)
	.DB	MID_MDRAM		; DEVICE MEDIA ID
	.DB	MD_ARAM			; DEVICE ATTRIBUTE
;
	DEVECHO	"MD: TYPE=RAM\n"
#ENDIF
;
#IF (MDROM)
MD_ROM_CFG:	; DEVICE 1 (ROM)
	.DW	MD_FNTBL		; DRIVER FUNCTION TABLE ADDRESS
	.DB	'D'			; DRIVER TYPE
	.DB	0			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY)
	.DB	1			; DRIVER UNIT NUMBER (1=ROM)
	.DB	ERR_NOTRDY		; DEVICE STATUS (HBIOS STATUS)
	.DW	MD_STR_TAG		; DRIVER TAG STRING PTR
	.DW	0,0			; CURRENT DISK ADDRESS (LBA)
	.DW	0,0			; DEVICE CAPACITY (BLOCKS, SET BY INITDEV)
	.DB	MID_MDROM		; DEVICE MEDIA ID
	.DB	MD_AROM			; DEVICE ATTRIBUTE (FLASH SET AT INIT)
;
	DEVECHO	"MD: TYPE=ROM\n"
#ENDIF
;
MD_DEVCNT	.EQU	($ - MD_CFGTBL) / MD_CFGSIZ
;
#IF ($ - MD_CFGTBL) != (MD_DEVCNT * MD_CFGSIZ)
	.ECHO	"*** INVALID MD CONFIG TABLE ***\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
;=============================================================================
; INITIALIZATION ENTRY POINT
;=============================================================================
;
MD_INIT:
#IF (MDFFENABLE)
	CALL	MD_FINIT		; PROBE FLASH CAPABILITY
#ENDIF
;
#IF (MDROM & MDFFENABLE)
	; IF FLASH FILESYSTEM CAPABLE, UPDATE ROM DEVICE ATTRIBUTE TO FLASH
	LD	A,(MD_FFSEN)		; NON-ZERO MEANS
	OR	A			; ... NOT FLASH
	JR	NZ,MD_INIT0		; ... FILESYSTEM CAPABLE
	LD	A,MD_AFSH		; UPDATE ROM DEVICE
	LD	(MD_ROM_CFG + MD_CFG_ATTRIB),A	; ... ATTRIBUTE TO FLASH
MD_INIT0:
#ENDIF
;
	; LOOP THRU CONFIG TABLE BY DEVICE COUNT.  WE DON'T TEST THE
	; FIRST BYTE OF EACH ENTRY FOR THE $FF END MARKER BECAUSE THAT
	; BYTE IS THE LSB OF THE FUNCTION TABLE ADDRESS, WHICH COULD BE $FF.
	LD	IY,MD_CFGTBL		; POINT TO START OF CONFIG TABLE
	LD	B,MD_DEVCNT		; DEVICE COUNT
	LD	A,B			; TEST FOR
	OR	A			; ... ZERO DEVICES
	RET	Z			; NOTHING TO DO
;
MD_INIT1:
	PUSH	BC			; SAVE LOOP COUNTER
	CALL	MD_INIT2		; REGISTER & INIT DEVICE
	POP	BC			; RESTORE LOOP COUNTER
	LD	DE,MD_CFGSIZ		; SIZE OF CFG TABLE ENTRY
	ADD	IY,DE			; BUMP POINTER
	DJNZ	MD_INIT1		; LOOP AS NEEDED
;
	XOR	A			; SUCCESS
	RET				; DONE
;
MD_INIT2:
	; ADD UNIT TO GLOBAL DISK UNIT TABLE
	LD	BC,MD_FNTBL		; BC := FUNC TABLE ADR
	PUSH	IY			; CFG ENTRY POINTER
	POP	DE			; COPY TO DE
	CALL	DIO_ADDENT		; ADD ENTRY TO GLOBAL DISK DEV TABLE
	LD	(IY+CFG_UNIT),A		; RECORD HBIOS UNIT NUMBER ASSIGNED
;
	CALL	MD_INITDEV		; INITIALIZE DEVICE
	PUSH	AF			; SAVE INIT STATUS
;
	CALL	DRV_PRTTAG		; TAG FOR ACTIVE DEVICE
	PRTS(" TYPE=$")			; LABEL FOR DEVICE TYPE
	LD	A,(IY+MD_CFG_ATTRIB)	; GET ATTRIBUTE
	LD	DE,MD_STR_RAM		; ASSUME RAM
	CP	MD_ARAM			; RAM?
	JR	Z,MD_INIT3		; IF SO, PRINT IT
	LD	DE,MD_STR_ROM		; ASSUME ROM
	CP	MD_AROM			; ROM?
	JR	Z,MD_INIT3		; IF SO, PRINT IT
	LD	DE,MD_STR_FLASH		; ELSE FLASH
MD_INIT3:
	CALL	WRITESTR		; PRINT TYPE
;
	POP	AF			; RECOVER INIT STATUS
	JR	Z,MD_INIT4		; IF Z, CONTINUE
	JP	ERR_PRT_SP		; ELSE ERROR TEXT AND ABORT
;
MD_INIT4:
	; PRINT STORAGE CAPACITY (BLOCK COUNT)
	PRTS(" BLOCKS=0x$")		; PRINT FIELD LABEL
	LD	A,CFG_DSKCAP		; OFFSET TO CAPACITY FIELD
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	LD32			; GET THE CAPACITY VALUE
	CALL	PRTHEX32		; PRINT HEX VALUE
;
	; PRINT STORAGE SIZE IN KB
	PRTS(" SIZE=$")			; PRINT FIELD LABEL
	LD	B,1			; 1 BIT SHIFT TO CONVERT BLOCKS --> KB
	CALL	SRL32			; RIGHT SHIFT
	CALL	PRTDEC32		; PRINT DWORD IN DECIMAL
	PRTS("KB$")			; PRINT SUFFIX
;
	XOR	A			; SUCCESS
	RET
;
;=============================================================================
; DRIVER FUNCTION TABLE
;=============================================================================
;
MD_FNTBL:
	.DW	MD_STATUS
	.DW	MD_RESET
	.DW	MD_SEEK
	.DW	MD_READ
	.DW	MD_WRITE
	.DW	MD_VERIFY
	.DW	MD_FORMAT
	.DW	MD_DEVICE
	.DW	MD_MEDIA
	.DW	MD_DEFMED
	.DW	MD_CAP
	.DW	MD_GEOM
#IF (($ - MD_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID MD FUNCTION TABLE ***\n"
#ENDIF
;
;
;
MD_VERIFY:
MD_FORMAT:
MD_DEFMED:
	SYSCHKERR(ERR_NOTIMPL)		; NOT IMPLEMENTED
	RET
;
;
;
MD_READ:
	CALL	HB_DSKREAD_NEW		; HOOK HBIOS DISK READ SUPERVISOR
	LD	BC,MD_RDSEC		; RAM / ROM SECTOR READ FUNC
#IF (MDFFENABLE)
	LD	A,(IY+MD_CFG_ATTRIB)	; GET ATTRIBUTE
	CP	MD_AFSH			; FLASH?
	JP	NZ,MD_IO		; IF NOT, DO THE IO
	LD	BC,MD_RDSECF		; FLASH SECTOR READ FUNC
#ENDIF
	JP	MD_IO			; DO THE IO
;
;
;
MD_WRITE:
	; ROM IS READ ONLY.  CHECK BEFORE HOOKING THE SUPERVISOR SO THAT
	; WE RETURN ZERO SECTORS WRITTEN AND DON'T FLAG A DEVICE ERROR.
	LD	A,(IY+MD_CFG_ATTRIB)	; GET ATTRIBUTE
	CP	MD_AROM			; ROM?
	JR	Z,MD_WRITE_RO		; IF SO, HANDLE READ ONLY
;
	CALL	HB_DSKWRITE_NEW		; HOOK HBIOS DISK WRITE SUPERVISOR
	LD	BC,MD_WRSEC		; RAM SECTOR WRITE FUNC
#IF (MDFFENABLE)
	LD	A,(IY+MD_CFG_ATTRIB)	; GET ATTRIBUTE
	CP	MD_AFSH			; FLASH?
	JP	NZ,MD_IO		; IF NOT, DO THE IO
	LD	BC,MD_WRSECF		; FLASH SECTOR WRITE FUNC
#ENDIF
	JP	MD_IO			; DO THE IO
;
MD_WRITE_RO:
	LD	E,0			; ZERO SECTORS WRITTEN
	LD	A,ERR_READONLY		; SIGNAL ERROR
	OR	A			; SET FLAGS
	RET				; AND DONE
;
;
;
MD_STATUS:
	LD	A,(IY+CFG_STATUS)	; GET STATUS OF SELECTED DEVICE
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
;
;
MD_RESET:
	JP	MD_INITDEV		; REINITIALIZE UNIT AND RETURN
;
;
;
MD_DEVICE:
	LD	D,DIODEV_MD		; D := DEVICE TYPE - ALL ARE MEMORY DISKS
	LD	E,(IY+CFG_DEVNUM)	; E := PHYSICAL DEVICE NUMBER
	LD	C,(IY+MD_CFG_ATTRIB)	; C := ATTRIBUTE
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,0			; L := 0, NO BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
;
;
MD_MEDIA:
	; CHECK IF MEDIA DISCOVERY REQUESTED
	BIT	0,E			; IF BIT 0 OF E, CHECK MEDIA
	LD	D,0			; SIGNAL NO MEDIA CHANGE
	JR	Z,MD_MEDIA_Z		; IF NOT SET, REPORT CURRENT INFO
;
	; CHECK CURRENT DEVICE STATUS
	LD	A,(IY+CFG_STATUS)	; GET OUR CURRENT STATUS
	OR	A			; SET FLAGS
	JR	Z,MD_MEDIA_Z		; IF OK, NOTHING MORE TO CHECK FOR MEMORY DISK
;
	; ATTEMPT TO RECOVER FROM ERROR STATE USING INITDEV
	; CURRENT STATUS WILL BE SET/CLEARED BY INITDEV
	CALL	MD_INITDEV		; PERFORM INIT
	LD	D,1			; SIGNAL MEDIA CHANGE
	; AND FALL THRU
;
MD_MEDIA_Z:
	LD	A,(IY+CFG_STATUS)	; GET CURRENT STATUS
	OR	A			; SET FLAGS
	LD	E,(IY+MD_CFG_MID)	; ASSUME DEVICE MEDIA ID
	RET	Z			; RETURN IF GOOD
	LD	E,MID_NONE		; ELSE SIGNAL NO MEDIA
	RET				; AND RETURN ERROR
;
;
;
MD_SEEK:
	JP	HB_DSKSEEKLBA		; USE GENERIC LBA SEEK ROUTINE
;
; GET DISK CAPACITY
;
MD_CAP:
	JP	HB_DSKCAP		; USE GENERIC CAPACITY ROUTINE
;
; GET DISK GEOMETRY
;
MD_GEOM:
	; RAM/ROM DISKS ALLOW CHS STYLE ACCESS BY EMULATING
	; A DISK DEVICE WITH 1 HEAD AND 16 SECTORS / TRACK.
	; THIS IS DIFFERENT FROM HB_DSKGEOMLBA (16 HEADS), SO WE
	; CAN'T USE THE GENERIC ROUTINE.
	CALL	HB_DSKCAP		; DE:HL := BLOCKS, BC := BLOCK SIZE, A := STATUS
	PUSH	AF			; SAVE STATUS
	LD	D,1 | $80		; HEADS / CYL := 1 BY DEFINITION, SET LBA CAPABILITY BIT
	LD	E,16			; SECTORS / TRACK := 16 BY DEFINITION
	LD	A,4			; PREPARE TO DIVIDE BY 16
MD_GEOM1:
	SRL	H			; SHIFT H
	RR	L			; SHIFT L
	DEC	A			; DEC LOOP COUNTER
	JR	NZ,MD_GEOM1		; DO 4 BITS TO DIVIDE BY 16
	POP	AF			; RECOVER STATUS
	RET				; DONE
;
;=============================================================================
; FUNCTION SUPPORT ROUTINES
;=============================================================================
;
; INITIALIZE OR REINITIALIZE DEVICE
; RETURN HBIOS RESULT CODE
;
; THERE IS NO HARDWARE TO RESET.  JUST (RE)COMPUTE THE CAPACITY FROM
; THE NUMBER OF RAM/ROM DISK BANKS AND MARK THE DEVICE READY.
; CFG_DSKADR IS NOT TOUCHED SINCE A RESET MAY OCCUR BETWEEN A SEEK
; AND THE SUBSEQUENT I/O.
;
MD_INITDEV:
	LD	A,(IY+CFG_DEVNUM)	; DEVICE NUMBER, 0=RAM, 1=ROM
	OR	A			; SET FLAGS
	LD	A,(CB_RAMD_BNKS)	; ASSUME RAM DISK BANKS
	JR	Z,MD_INITDEV1		; IF RAM, GOT IT
	LD	A,(CB_ROMD_BNKS)	; ELSE ROM DISK BANKS
MD_INITDEV1:
	; BLOCKS = BANKS * 64 (32K BANK / 512 BYTE BLOCK)
	LD	L,A			; BANKS TO HL
	LD	H,0			; ...
	ADD	HL,HL			; X2
	ADD	HL,HL			; X4
	ADD	HL,HL			; X8
	ADD	HL,HL			; X16
	ADD	HL,HL			; X32
	ADD	HL,HL			; X64
	LD	(IY+CFG_DSKCAP+0),L	; SAVE CAPACITY
	LD	(IY+CFG_DSKCAP+1),H	; ...
	XOR	A			; ... HIGH WORD
	LD	(IY+CFG_DSKCAP+2),A	; ... IS ALWAYS
	LD	(IY+CFG_DSKCAP+3),A	; ... ZERO
;
	LD	(IY+CFG_STATUS),A	; STATUS := OK (A IS ZERO)
	RET				; DONE, A=0, ZF SET
;
; PERFORM SECTOR READ/WRITE
; ON ENTRY, BC=SECTOR READ/WRITE FUNCTION, HL=DATA BUFFER
; RETURN HBIOS RESULT CODE
;
MD_IO:
	LD	(MD_DSKBUF),HL		; SAVE DISK BUFFER ADDRESS
	LD	H,B			; SECTOR FUNC
	LD	L,C			; ... TO HL
#IF (MDFFENABLE)
	PUSH	IX			; FLASH ROUTINES USE IX
	CALL	JPHL			; DO THE SECTOR READ/WRITE
	POP	IX			; RESTORE IX
#ELSE
	CALL	JPHL			; DO THE SECTOR READ/WRITE
#ENDIF
	JP	NZ,MD_ERR		; HANDLE ERROR AND RETURN
;
	CALL	HB_DSKINCLBA		; INCREMENT LBA
;
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
; HANDLE AN I/O ERROR.  ALL MD SECTOR ERRORS (OUT OF RANGE, FLASH
; ERASE/VERIFY FAILURE, DMA ERROR) ARE MAPPED TO HBIOS IO ERROR.
; THE ERROR IS RECORDED AS THE PERSISTENT DEVICE STATUS, SO THE
; NEXT I/O WILL REINITIALIZE THE DEVICE VIA THE DISK SUPERVISOR.
;
MD_ERR:
	LD	A,ERR_IO		; HBIOS ERR TO ACCUM
	LD	(IY+CFG_STATUS),A	; SET PERSISTENT STATUS
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
; READ FLASH
;
#IF (MDFFENABLE)
MD_RDSECF:				; CALLED FROM MD_RW
;
	CALL	MD_IOSETUPF		; SETUP SOURCE ADDRESS
;
	PUSH	HL			; IS THE SECTOR
	LD	HL,(MD_LBA4K)		; WE WANT TO
	XOR	A			; READ ALREADY
	SBC	HL,BC			; IN THE 4K
	POP	HL			; BLOCK WE HAVE
	JR	Z,MD_SECM		; IN THE BUFFER?
;
					; DESIRED SECTOR IS NOT IN BUFFER
	LD	(MD_LBA4K),BC		; WE WILL READ IN A NEW 4K SECTOR.
					; SAVE THE 4K LBA FOR FUTURE CHECKS
;
	CALL	MD_CALBAS		; SETUP BANK AND SECTOR
	RET	NZ			; RETURN IF ERROR
;
	LD	IX,MD_F4KBUF		; SET DESTINATION ADDRESS
	LD	HL,MD_FREAD_R		; PUT ROUTINE TO CALL
	CALL	MD_FNCALL		; EXECUTE: READ 4K SECTOR
;
MD_SECM:
	LD	A,(IY+CFG_DSKADR+0)	; GET SECTOR WITHIN 4K BLOCK
	AND	%00000111		; AND CALCULATE OFFSET OFFSET
	ADD	A,A
	LD	D,A			; FROM THE START
	LD	E,0
;
	LD	HL,MD_F4KBUF		; POINT TO THE SECTOR WE
	ADD	HL,DE			; WANT TO COPY
	LD	DE,(MD_DSKBUF)
;
#IF (DMAENABLE & (DMAMODE!=DMAMODE_NONE))
#IF (DMA_FBACK)
	LD	A,(DMA_FAIL_FLAG)
	OR	A
	JR	NZ,MD_NODMA
#ENDIF
	LD	BC,512-1		; COPY ONE 512B SECTOR FROM THE
	JP	DMALDIR			; 4K SECTOR TO THE DISK BUFFER
#ENDIF
MD_NODMA:
#IF (!(DMAENABLE & (DMAMODE!=DMAMODE_NONE)))
	LD	BC,512			; COPY ONE 512B SECTOR FROM THE
	LDIR				; 4K SECTOR TO THE DISK BUFFER
	XOR	A
	RET
#ELSE
#IF  (DMA_FBACK)
	LD	BC,512			; COPY ONE 512B SECTOR FROM THE
	LDIR				; 4K SECTOR TO THE DISK BUFFER
	XOR	A
	RET
#ENDIF
#ENDIF
;
; SETUP DE:HL AS THE SECTOR ADDRESS TO READ OR WRITE
;
; ON EXIT
;  BC    = LBA 4K BLOCK WE ARE ACCESSING
;  DE:HL = MEMORY ADDRESS TO ACCESS IN FLASH
;
MD_IOSETUPF:
	LD	L,(IY+CFG_DSKADR+0)	; HL := LOW WORD OF LBA
	LD	H,(IY+CFG_DSKADR+1)
	INC	H			; SKIP FIRST 128MB (256 SECTORS)
;
	LD	A,L			; SAVE LBA 4K
	AND	%11111000		; BLOCK WE ARE
	LD	C,A			; GOING TO
	LD	B,H			; ACCESS
;
	LD	D,0			; CONVERT LBA
	LD	E,H			; TO ADDRESS
	LD	H,L			; MULTIPLY BY 512
	LD	L,D			; DE:HL = HLX512
	SLA	H
	RL	E
	RL	D
;
	RET
;
;======================================================================
; CALCULATE BANK AND ADDRESS DATA FROM MEMORY ADDRESS
;
; ON ENTRY DE:HL CONTAINS 32 BIT MEMORY ADDRESS.
; ON EXIT  B     CONTAINS BANK SELECT BYTE
;          C     CONTAINS HIGH BYTE OF SECTOR ADDRESS
;
; DDDDDDDDEEEEEEEE HHHHHHHHLLLLLLLL
; 3322222222221111 1111110000000000
; 1098765432109876 5432109876543210
; XXXXXXXXXXXXSSSS SSSSXXXXXXXXXXXX < S = SECTOR
; XXXXXXXXXXXXBBBB BXXXXXXXXXXXXXXX < B = BANK
;======================================================================
;
MD_CALBAS:
;
#IF (MD_FDBG==1)
	CALL	PC_SPACE		; DISPLAY SECTOR
	CALL	PRTHEX32		; SECTOR ADDRESS
	CALL	PC_SPACE		; IN DE:HL
#ENDIF
;
	PUSH	HL
	LD	A,E			; BOTTOM PORTION OF SECTOR
	AND	$0F			; ADDRESS THAT GETS WRITTEN
	RLC	H			; WITH ERASE COMMAND BYTE
	RLA				; A15 GETS DROPPED OFF AND
	LD	B,A			; ADDED TO BANK SELECT
;
	LD	A,H			; TOP SECTION OF SECTOR
	RRA				; ADDRESS THAT GETS WRITTEN
	AND	$70			; TO BANK SELECT PORT
	LD	C,A

	POP	HL
;
	LD	(MD_FBAS),BC		; SAVE BANK AND SECTOR FOR USE IN FLASH ROUTINES
;
#IF (MD_FDBG==1)
	CALL	PRTHEXWORD		; DISPLAY BANK AND
	CALL	PC_SPACE		; SECTOR RESULT
#ENDIF
;
	; CHECK FOR ACCESS BEYOND AVAILABLE ROM BANKS
	LD	A,B			; BANK ID TO ACCUM
	SUB	BID_ROMD0		; ZERO OFFSET
	CP	ROMD_BNKS		; CHECK FOR OUT OF BOUNDS
	JR	C,MD_CALBAS1		; IF NOT, CONTINUE
	LD	A,ERR_IO		; ELSE SIGNAL IO ERROR
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
MD_CALBAS1:
	XOR	A			; SIGNAL SUCCESS
	RET
;
; WRITE FLASH
;
MD_WRSECF:				; CALLED FROM MD_RW
	CALL	MD_IOSETUPF		; SETUP DESTINATION ADDRESS
;
	PUSH	HL			; IS THE SECTOR
	LD	HL,(MD_LBA4K)		; WE WANT TO
	XOR	A			; WRITE ALREADY
	SBC	HL,BC			; IN THE 4K
	POP	HL			; BLOCK WE HAVE
	JR	Z,MD_SECM1		; IN THE BUFFER
;
	LD	(MD_LBA4K),BC		; SAVE 4K LBA
;
	CALL	MD_CALBAS		; SETUP BANK AND SECTOR
	RET	NZ			; RETURN ON ERROR
;
	LD	IX,MD_F4KBUF		; SET DESTINATION ADDRESS
	LD	HL,MD_FREAD_R		; PUT ROUTINE TO CALL
	CALL	MD_FNCALL		; EXECUTE: READ 4K SECTOR
;
MD_SECM1:				; DESIRED SECTOR IS IN BUFFER
	LD	HL,MD_FERAS_R		; PUT ROUTINE TO CALL
	CALL	MD_FNCALL		; EXECUTE: ERASE 4K SECTOR
	OR	A
	RET	NZ			; RETURN IF ERROR
	;
	; COPY 512B SECTOR INTO 4K SECTOR
	;
	LD	A,(IY+CFG_DSKADR+0)	; GET SECTOR WITHIN 4K BLOCK
	AND	%00000111		; AND CALCULATE OFFSET OFFSET
	ADD	A,A
	LD	D,A			; FROM THE START
	LD	E,0
;
	LD	HL,MD_F4KBUF		; POINT TO THE SECTOR WE
	ADD	HL,DE			; WANT TO COPY
	EX	DE,HL
;
	LD	HL,(MD_DSKBUF)
#IF (DMAENABLE & (DMAMODE!=DMAMODE_NONE))
#IF (DMA_FBACK)
	LD	A,(DMA_FAIL_FLAG)
	OR	A
	JR	NZ,MD_NODMA1
#ENDIF
	LD	BC,512-1		; COPY ONE 512B SECTOR FROM THE
	CALL	DMALDIR			; THE DISK BUFFER TO 4K SECTOR
	RET	NZ			; EXIT IF DMA COPY ERROR
	JR	MD_NODMAERR
#ENDIF
MD_NODMA1:
#IF (!(DMAENABLE & (DMAMODE!=DMAMODE_NONE)))
	LD	BC,512			; COPY ONE 512B SECTOR FROM THE
	LDIR
#ELSE
#IF  (DMA_FBACK)			; THE DISK BUFFER TO 4K SECTOR
	LD	BC,512
	LDIR
#ENDIF
#ENDIF
MD_NODMAERR:
	LD	IX,MD_F4KBUF		; SET SOURCE ADDRESS
	LD	HL,MD_FWRIT_R		; PUT ROUTINE TO CALL
	CALL	MD_FNCALL		; EXECUTE: WRITE 4K SECTOR
;
	XOR	A			; PRESUME SUCCESS STATUS
;
#IF (MD_FVAR==1)
	LD	IX,MD_F4KBUF		; SET SOURCE ADDRESS
	LD	HL,MD_FVERI_R		; PUT ROUTINE TO CALL
	CALL	MD_FNCALL		; EXECUTE: VERIFY 4K SECTOR
;
	OR	A
	RET	Z			; RETURN IF SUCCESSFUL
;
	LD	IX,MD_F4KBUF		; SET SOURCE ADDRESS		; RETRY
	LD	HL,MD_FWRIT_R		; PUT ROUTINE TO CALL		; WRITE
	CALL	MD_FNCALL		; EXECUTE: WRITE 4K SECTOR	; ONCE
;
	LD	IX,MD_F4KBUF		; SET SOURCE ADDRESS		; VERIFY
	LD	HL,MD_FVERI_R		; PUT ROUTINE TO CALL		; AGAIN
	CALL	MD_FNCALL		; EXECUTE: VERIFY 4K SECTOR
;
	OR	A			; SET FINAL STATUS AFTER RETRY
#ENDIF
;
	RET
;
MD_LBA4K	.DW	$FFFF		; LBA OF CURRENT SECTOR
MD_FBAS		.DW	$FFFF		; BANK AND SECTOR
#ENDIF
;
; READ RAM / ROM
;
MD_RDSEC:
	CALL	MD_IOSETUP		; SETUP FOR MEMORY COPY
	CP	$FF			; ERROR?
	JR	NZ,MD_RDSEC1		; IF NOT, CONTINUE
	LD	A,ERR_IO		; SIGNAL IO ERROR
	OR	A			; SET FLAGS
	RET				; AND DONE
MD_RDSEC1:
#IF (MDTRACE >= 2)
	LD	(MD_SRC),HL
	LD	(MD_DST),DE
	LD	(MD_LEN),BC
#ENDIF
	PUSH	BC
	LD	C,A			; SOURCE BANK
	LD	B,BID_BIOS		; DESTINATION BANK IS RAM BANK 1 (HBIOS)
#IF (MDTRACE >= 2)
	LD	(MD_SRCBNK),BC
	CALL	MD_PRT
#ENDIF
	LD	A,C			; GET SOURCE BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,B			; GET DESTINATION BANK
	LD	(HB_DSTBNK),A		; SET IT
	POP	BC
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY		; DO THE INTERBANK COPY
#IF (INTMODE == 1)
	EI
#ENDIF
	XOR	A
	RET
;
; WRITE RAM
;
MD_WRSEC:
	CALL	MD_IOSETUP		; SETUP FOR MEMORY COPY
	CP	$FF			; ERROR?
	JR	NZ,MD_WRSEC1		; IF NOT, CONTINUE
	LD	A,ERR_IO		; SIGNAL IO ERROR
	OR	A			; SET FLAGS
	RET				; AND DONE
MD_WRSEC1:
	EX	DE,HL			; SWAP SRC/DEST FOR WRITE
#IF (MDTRACE >= 2)
	LD	(MD_SRC),HL
	LD	(MD_DST),DE
	LD	(MD_LEN),BC
#ENDIF
	PUSH	BC
	LD	C,BID_BIOS		; SOURCE BANK IS RAM BANK 1 (HBIOS)
	LD	B,A			; DESTINATION BANK
#IF (MDTRACE >= 2)
	LD	(MD_SRCBNK),BC
	CALL	MD_PRT
#ENDIF
	LD	A,C			; GET SOURCE BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,B			; GET DESTINATION BANK
	LD	(HB_DSTBNK),A		; SET IT
	POP	BC
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY		; DO THE INTERBANK COPY
#IF (INTMODE == 1)
	EI
#ENDIF
	XOR	A
	RET
;
; SETUP FOR MEMORY COPY
;   A=BANK SELECT
;   BC=COPY SIZE
;   DE=DESTINATION
;   HL=SOURCE
;
; ASSUMES A "READ" OPERATION.  HL AND DE CAN BE SWAPPED
; AFTERWARDS TO ACHIEVE A WRITE OPERATION
;
; ON INPUT, WE HAVE LBA ADDRESSING IN HSTLBAHI:HSTLBALO
; BUT WE NEVER HAVE MORE THAN $FFFF BLOCKS IN A RAM/ROM DISK,
; SO THE HIGH WORD (HSTLBAHI) IS IGNORED
;
; EACH RAM/ROM BANK IS 32K BY DEFINITION AND EACH SECTOR IS 512
; BYTES BY DEFINITION.	SO, EACH RAM/ROM BANK CONTAINS 64 SECTORS
; (32,768 / 512 = 64).	THEREFORE, YOU CAN THINK OF LBA AS
; 00000BBB:BBOOOOOO IS WHERE THE 'B' BITS REPRESENT THE BANK NUMBER
; AND THE 'O' BITS REPRESENT THE SECTOR NUMBER WITHIN THE BANK.
;
; TO EXTRACT THE BANK NUMBER, WE CAN LEFT SHIFT TWICE TO GIVE US:
; 000BBBBB:OOOOOOOO.  FROM THIS WE CAN EXTRACT THE MSB
; TO USE AS THE BANK NUMBER.  NOTE THAT THE "RAW" BANK NUMBER MUST THEN
; BE OFFSET TO THE START OF THE ROM/RAM BANKS.
; ALSO NOTE THAT THE HIGH BIT OF THE BANK NUMBER REPRESENTS "RAM" SO THIS
; BIT MUST ALSO BE SET ACCORDING TO THE UNIT BEING ADDRESSED.
;
; TO GET THE BYTE OFFSET, WE THEN RIGHT SHIFT THE LSB BY 1 TO GIVE US:
; 0OOOOOOO AND EXTRACT THE LSB TO REPRESENT THE MSB OF
; THE BYTE OFFSET.  THE LSB OF THE BYTE OFFSET IS ALWAYS 0 SINCE WE ARE
; DEALING WITH 512 BYTE BOUNDARIES.
;
MD_IOSETUP:
	LD	L,(IY+CFG_DSKADR+0)	; HL := LOW WORD OF LBA
	LD	H,(IY+CFG_DSKADR+1)	; ...
	; ALIGN BITS TO EXTRACT BANK NUMBER FROM H
	SLA	L			; LEFT SHIFT ONE BIT
	RL	H			;   FULL WORD
	SLA	L			; LEFT SHIFT ONE BIT
	RL	H			;   FULL WORD
	LD	C,H			; BANK NUMBER FROM H TO C
	; GET BANK NUM TO A AND SET FLAG Z=RAM (DEV 0), NZ=ROM (DEV 1)
	LD	A,(IY+CFG_DEVNUM)	; DEVICE TO A
	AND	$01			; ISOLATE LOW BIT, SET ZF
	LD	A,C			; BANK VALUE INTO A
	PUSH	AF			; SAVE IT FOR NOW
	; ADJUST L TO HAVE MSB OF OFFSET
	SRL	L			; ADJUST L TO BE MSB OF BYTE OFFSET
	LD	H,L			; MOVE MSB TO H WHERE IT BELONGS
	LD	L,0			;   AND ZERO L SO HL IS NOW BYTE OFFSET
	; LOAD DESTINATION AND COUNT
	LD	DE,(MD_DSKBUF)		; DMA ADDRESS IS DESTINATION
	LD	BC,512			; ALWAYS COPY ONE SECTOR
	; FINISH UP
	POP	AF			; GET BANK AND FLAGS BACK
	JR	Z,MD_IOSETUP2		; DO RAM DRIVE, ELSE FALL THRU FOR ROM DRIVE
;
MD_IOSETUP1:	; ROM
	CP	ROMD_BNKS		; WITHIN AVAILABLE ROM DISK BANKS?
	JR	NC,MD_IOSETUP3		; HANDLE OUT OF BOUNDS
	ADD	A,BID_ROMD0
	RET
;
MD_IOSETUP2:	; RAM
	CP	RAMD_BNKS		; WITHIN AVAILABLE RAM DISK BANKS?
	JR	NC,MD_IOSETUP3		; HANDLE OUT OF BOUNDS
	ADD	A,BID_RAMD0
	RET
;
MD_IOSETUP3:
	OR	$FF			; SIGNAL ERROR
	RET				; DONE
;
;
;
#IF (MDTRACE >= 2)
MD_PRT:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
;
	CALL	NEWLINE
;
	LD	DE,MDSTR_PREFIX
	CALL	WRITESTR
;
	CALL	PC_SPACE
	LD	DE,MDSTR_SRC
	CALL	WRITESTR
	LD	A,(MD_SRCBNK)
	CALL	PRTHEXBYTE
	CALL	PC_COLON
	LD	BC,(MD_SRC)
	CALL	PRTHEXWORD
;
	CALL	PC_SPACE
	LD	DE,MDSTR_DST
	CALL	WRITESTR
	LD	A,(MD_DSTBNK)
	CALL	PRTHEXBYTE
	CALL	PC_COLON
	LD	BC,(MD_DST)
	CALL	PRTHEXWORD
;
	CALL	PC_SPACE
	LD	DE,MDSTR_LEN
	CALL	WRITESTR
	LD	BC,(MD_LEN)
	CALL	PRTHEXWORD
;
	POP	HL
	POP	DE
	POP	BC
	POP	AF
;
	RET
;
MDSTR_PREFIX	.TEXT	"MD:$"
MDSTR_SRC	.TEXT	"SRC=$"
MDSTR_DST	.TEXT	"DEST=$"
MDSTR_LEN	.TEXT	"LEN=$"
#ENDIF
