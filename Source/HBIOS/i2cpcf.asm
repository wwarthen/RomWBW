	ADD	A,'0'
	INC	(HL)
	CALL	COUT
	LD	A,']'
	CALL	COUT
	POP 	HL
	POP  	DE
	POP  	AF
	RET
I2CPCF_DBGF:
	.DB	0		; DEBUG STAGE COUNTER
#ENDIF
;
I2CPCF_NOPCF	.DB	"NOT PRESENT$"
I2CPCF_WRTFAIL	.DB	"SETTING DEVICE ID FAILED$"
I2CPCF_REGFAIL 	.DB	"CLOCK REGISTER SELECT ERROR$"
I2CPCF_CLKFAIL 	.DB	"CLOCK SET FAIL$"
I2CPCF_IDLFAIL 	.DB	"BUS IDLE FAILED$"
