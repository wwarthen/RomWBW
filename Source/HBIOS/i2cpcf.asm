;==================================================================================================
; PCF8584 I2C DRIVER
;==================================================================================================
;
#IF (I2CBITENABLE)
	.ECHO	"*** I2CBIT DRIVER CANNOT BE USED WITH I2CPCF DRIVER!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
I2CPCF_BASE  	.EQU  I2CPCFBASE
I2CPCF_ID   	.EQU  0AAH
;
I2CPCF_RS0	.EQU  I2CPCF_BASE
I2CPCF_RS1	.EQU  I2CPCF_BASE+1
I2CPCF_OWN		.EQU  (I2CPCF_ID >> 1)	 	; PCF'S ADDRESS IN SLAVE MODE
;
;T4LC512D	.EQU	10100000B		; DEVICE IDENTIFIER
;T4LC512A1	.EQU	00000000B		; DEVICE ADDRESS
;T4LC512A2	.EQU	00001110B		; DEVICE ADDRESS
;T4LC512A3	.EQU	00000010B		; DEVICE ADDRESS
;T4LC512W	.EQU	00000000B		; DEVICE WRITE
;T4LC512R	.EQU	00000001B		; DEVICE READ
;
;I2CDEV1W  	.EQU	(T4LC512D+T4LC512A1+T4LC512W)
;I2CDEV1R	.EQU	(T4LC512D+T4LC512A1+T4LC512R)
;
;I2CDEV2W  	.EQU	(T4LC512D+T4LC512A2+T4LC512W)
;I2CDEV2R	.EQU	(T4LC512D+T4LC512A2+T4LC512R)
;
;I2CDEV3W  	.EQU	(T4LC512D+T4LC512A3+T4LC512W)
;I2CDEV3R	.EQU	(T4LC512D+T4LC512A3+T4LC512R)
;
; CONTROL REGISTER BITS
;
I2CPCF_PIN  	.EQU  10000000B
I2CPCF_ES0  	.EQU  01000000B
I2CPCF_ES1  	.EQU  00100000B
I2CPCF_ES2  	.EQU  00010000B
I2CPCF_EN1  	.EQU  00001000B
I2CPCF_STA  	.EQU  00000100B
I2CPCF_STO  	.EQU  00000010B
I2CPCF_ACK  	.EQU  00000001B
;
I2CPCF_START_		.EQU  (I2CPCF_PIN | I2CPCF_ES0 | I2CPCF_STA | I2CPCF_ACK)
I2CPCF_STOP_		.EQU  (I2CPCF_PIN | I2CPCF_ES0 | I2CPCF_STO | I2CPCF_ACK)
I2CPCF_REPSTART_ 	.EQU  (I2CPCF_ES0 | I2CPCF_STA | I2CPCF_ACK)
I2CPCF_IDLE_		.EQU  (I2CPCF_PIN | I2CPCF_ES0 | I2CPCF_ACK)
;
; STATUS REGISTER BITS
;
;I2CPCF_PIN  	.EQU  10000000B
I2CPCF_INI   	.EQU  01000000B   ; 1 if not initialized
I2CPCF_STS   	.EQU  00100000B
I2CPCF_BER   	.EQU  00010000B
I2CPCF_AD0   	.EQU  00001000B
I2CPCF_LRB   	.EQU  00001000B
I2CPCF_AAS   	.EQU  00000100B
I2CPCF_LAB   	.EQU  00000010B
I2CPCF_BB		.EQU  00000001B
;
; THE PCF8584 TARGETS A TOP I2C CLOCK SPEED OF 90KHZ AND SUPPORTS DIVIDERS FOR
; 3, 4.43, 6, 8 AND 12MHZ TO ACHEIVE THIS.
;
; +--------------------------------------------------------------------------------------------+
; | div/clk |  2MHz |  4MHz  |  6MHz | 7.38Mhz |  10MHz | 12MHz |  16MHz | 18.432Mhz |  20MHz  |
; +----------------------------------------------------------------------------------+---------+
; |   3MHz  | 60Khz | 120Khz |       |         |        |       |        |           |         |
; | 4.43MHz |       |  81Khz |       |         |        |       |        |           |         |
; |   6MHz  |       |        | 90Khz | 110Khz  |        |       |        |           |         |
; |   8MHz  |       |        |       |  83Khz  | 112Khz |       |        |           |         |
; |  12MHz  |       |        |       |         |        | 90Khz | 120Khz |   138Khz  |  150Khz |
; +----------------------------------------------------------------------------------+---------+
;
; SEE STD.ASM FOR DEFINITIONS OF I2CPCFCLK AND I2CPCFTRNS VALUES
;
I2CPCF_CLK	.EQU	I2CPCFCLK
I2CPCF_TRNS	.EQU	I2CPCFTRNS
;
; TIMEOUT AND DELAY VALUES (ARBITRARY)
;
I2CPCF_PINTO	.EQU	65000
I2CPCF_ACKTO	.EQU	65000
I2CPCF_BBTO	.EQU	65000
I2CPCF_LABDLY	.EQU	65000
;
	DEVECHO	"I2CPCF: IO="
	DEVECHO	I2CPCF_BASE
	DEVECHO	"\n"
;
; DATA PORT REGISTERS
;
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_I2CPCF	.EQU	$
;
	.DW	SIZ_I2CPCF		; MODULE SIZE
	.DW	I2CPCF_INITPHASE	; ADR OF INIT PHASE HANDLER
;
I2CPCF_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	;CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	;JP	Z,I2CPCF_PREINIT	; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,I2CPCF_INIT		; DO INIT
	RET				; DONE
;
;
;
I2CPCF_INIT:
	CALL	NEWLINE			; Formatting
	PRTS("I2CPCF: IO=0x$")
	LD	A, I2CPCF_BASE
	CALL	PRTHEXBYTE
	CALL	PC_SPACE
	CALL	I2CPCF_INITDEV
	;CALL	NEWLINE
	RET
;
; LINUX DRIVER BASED CODE
;
;	I2C_INB		= IN A,(I2CPCF_RS0)
;	I2C_OUTB	= LD A,* | OUT (I2CPCF_RS0),A
;	SET_I2CPCF	-= LD A,* | OUT (PCF_RS1),A
;	GET_I2CPCF	= IN A,(PCF_RS1)
;
;-----------------------------------------------------------------------------
;
I2C_START_ADDR:
	OUT	(I2CPCF_RS0),A
I2C_START:
	LD	A,I2CPCF_START_
	OUT	(I2CPCF_RS1),A
	RET
;
;-----------------------------------------------------------------------------
I2C_REPSTART:
	LD	A,I2CPCF_REPSTART_
	OUT	(I2CPCF_RS1),A
	RET
;
;-----------------------------------------------------------------------------
I2C_STOP:
	LD   	A,I2CPCF_STOP_
	OUT  	(I2CPCF_RS1),A
	RET
;
;-----------------------------------------------------------------------------
; PUT ONE BYTE ON THE I2C BUS
; A = BYTE. DOES NOT WAIT/CHECK ACK OR PIN
;
I2C_PUTBYTE:
	OUT	(I2CPCF_RS0),A
	RET
;
;-----------------------------------------------------------------------------
; GET ONE BYTE OFF THE I2C BUS
; CALLER MUST HAVE ALREADY WAITED FOR PIN
; RETURNS BYTE IN A
;
I2C_GETBYTE:
	IN	A,(I2CPCF_RS0)
	RET
;
;-----------------------------------------------------------------------------
; PREP NEGATIVE ACKNOWLEDGE FOR THE NEXT BYTE READ
; MASTER RECEIVER MODE, LAST BYTE OF A READ
; SEE PCF8584 DATASHEET FIG.7
;
I2C_PREPNACK:
	LD	A,I2CPCF_ES0
	OUT	(I2CPCF_RS1),A
	RET
;
;-----------------------------------------------------------------------------
;
I2CPCF_INITDEV:
	LD	A,I2CPCF_PIN   	; S1=80H: S0 SELECTED, SERIAL
	OUT	(I2CPCF_RS1),A	; INTERFACE OFF
	NOP
	IN	A,(I2CPCF_RS1)	; CHECK TO SEE S1 NOW USED AS R/W
	;CALL	PC_SPACE
	;CALL	PRTHEXBYTE
	AND	07FH	  	; CTRL. PCF8584 DOES THAT WHEN ESO
	JR	NZ,I2CPCF_FAIL	; IS ZERO
;
	LD	A,I2CPCF_OWN	; LOAD OWN ADDRESS IN S0,
	OUT	(I2CPCF_RS0),A	; EFFECTIVE ADDRESS IS (OWN <<1)
	NOP
	IN	A,(I2CPCF_RS0)	; CHECK IT IS REALLY WRITTEN
	;CALL	PC_SPACE
	;CALL	PRTHEXBYTE
	CP	I2CPCF_OWN
	JP	NZ,I2CPCF_SETERR
;
	LD	A,+(I2CPCF_PIN | I2CPCF_ES1)	; S1=0A0H
	OUT	(I2CPCF_RS1),A		; NEXT BYTE IN S2
	NOP
	IN	A,(I2CPCF_RS1)
	;CALL	PC_SPACE
	;CALL	PRTHEXBYTE
	AND	07FH
	CP	I2CPCF_ES1
	JP	NZ,I2CPCF_REGERR
;
	LD	A,I2CPCF_CLK | I2CPCF_TRNS	; LOAD CLOCK REGISTER S2
	OUT	(I2CPCF_RS0),A
	NOP
	IN	A,(I2CPCF_RS0)	; CHECK IT'S REALLY WRITTEN, ONLY
	;CALL	PC_SPACE
	;CALL	PRTHEXBYTE
	AND	1FH	   	; THE LOWER 5 BITS MATTER
	CP	I2CPCF_CLK
	JP	NZ,I2CPCF_CLKERR
;
	LD	A,I2CPCF_IDLE_
	OUT	(I2CPCF_RS1),A
	NOP
	IN	A,(I2CPCF_RS1)
	;CALL	PC_SPACE
	;CALL	PRTHEXBYTE
	CP	+(I2CPCF_PIN | I2CPCF_BB)
	JP	NZ,I2CPCF_IDLERR
;
	XOR	A
	RET
;
I2CPCF_FAIL:
	CALL  I2CPCF_INIERR
	LD	A,ERR_NOHW
	LD	(I2C_FAIL_FLAG),A
	RET
;
I2C_FAIL_FLAG:
	.DB	0
;
;-----------------------------------------------------------------------------
I2CPCF_HANDLE_LAB:
;
	LD	A,I2CPCF_PIN
	OUT	(I2CPCF_RS1),A
	LD	A,I2CPCF_ES0
	OUT	(I2CPCF_RS1),A
;
	LD	HL,I2CPCF_LABDLY
I2CPCF_LABLP:
	LD	A,H
	OR	L
	DEC	HL
	JR	NZ,I2CPCF_LABLP
;
	IN	A,(I2CPCF_RS1)
	RET
;
;-----------------------------------------------------------------------------
; PUT ONE BYTE ON THE I2C BUS
; A = BYTE. DOES WAIT/CHECK PIN
;
I2C_PUTBYTE_PIN:
	OUT	(I2CPCF_RS0),A
;
;-----------------------------------------------------------------------------
;
; RETURN A=00/Z  IF SUCCESSFULL
; RETURN A=FF/NZ IF TIMEOUT
; RETURN A=01/NZ IF LOST ARBITRATION
; I2CPCF_STATUS HOLDS LAST PCF STATUS
;
I2C_WAIT_FOR_PIN:
	PUSH	HL
	LD	HL,I2CPCF_PINTO					; SET TIMEOUT VALUE

I2CPCF_WFP0:
	IN	A,(I2CPCF_RS1)					; GET BUS
	LD	(I2CPCF_STATUS),A				; STATUS
	LD	B,A

	DEC	HL						; HAVE WE
	LD	A,H						; TIMED OUT
	OR	L
	JR	Z,I2CPCF_WFP1					; YES WE HAVE, GO ACTION IT

	LD	A,B						;
	AND	I2CPCF_PIN					; IS TRANSMISSION COMPLETE?
	JR	NZ,I2CPCF_WFP0					; KEEP ASKING IF NOT OR
	POP	HL						; YES COMPLETE (PIN=0) RETURN WITH ZERO
	RET
I2CPCF_WFP1:
	LD	A,B						; DID WE LOSE ARBITRATION?
	AND	I2CPCF_LAB						; IF A=0 THEN NO
	CPL
	JR	NZ,I2CPCF_WFP2					; NO
	CALL	I2CPCF_HANDLE_LAB				; YES GO HANDLE IT
	LD	(I2CPCF_STATUS),A
	XOR	A						; RETURN NZ, A=01H
	INC	A
I2CPCF_WFP2:
	POP	HL		  				; RET NZ, A=FF IF TIMEOUT
	RET
;
I2CPCF_STATUS	.DB	00H

;
;-----------------------------------------------------------------------------
; PUT ONE BYTE ON THE I2C BUS
; A = BYTE. DOES WAIT/CHECK ACK
;
I2C_PUTBYTE_ACK:
	OUT	(I2CPCF_RS0),A

;--------------------------------------------------------------------------------
;
; RETURN NZ/FF IF TIMEOUT ERROR
; RETURN NZ/01 IF FAILED TO RECEIVE ACKNOWLEDGE
; RETURN Z/00  IF RECEIVED ACKNOWLEDGE
;
I2C_WAIT_FOR_ACK:
	PUSH	HL
	PUSH	BC
	LD	HL,I2CPCF_ACKTO
;
I2CPCF_WFA0:
	IN	A,(I2CPCF_RS1)	; READ PIN
	LD	(I2CPCF_STATUS),A	; STATUS
	LD	B,A
;
	DEC	HL		; SEE IF WE HAVE TIMED
	LD	A,H		; OUT WAITING FOR PIN
	OR	L		; EXIT IF
	JR	Z,I2CPCF_WFA1	; WE HAVE
;
	LD	A,B		; OTHERWISE KEEP LOOPING
	AND	I2CPCF_PIN		; UNTIL WE GET PIN
	JR	NZ,I2CPCF_WFA0	; OR TIMEOUT
;
	LD	A,B		; WE GOT PIN SO NOW
	AND	I2CPCF_LRB	; CHECK WE HAVE
	JR	Z,I2CPCF_WFA_ACK	; BIT CLEAR = ACK RECEIVED
	LD	A,1		; NO ACK -- FAILURE REASON = 01
	OR	A		; FORCE NZ
	JR	I2CPCF_WFA2
I2CPCF_WFA_ACK:
	XOR	A		; A=00 -- ACK RECEIVED, FORCE Z
	JR	I2CPCF_WFA2
I2CPCF_WFA1:
	LD	A,0FFH		; TIMEOUT -- FAILURE REASON = FF
	OR	A		; FORCE NZ
I2CPCF_WFA2:
	POP	BC
	POP	HL
	RET
;
;--------------------------------------------------------------------------------
;
;	HL POINTS TO DATA
;	DE = COUNT
;	A = 0 LAST A=1 NOT LAST
;
;
;I2C_READBYTES:			; NOT FUNCTIONAL YET

	LD	(I2CPCF_LBF),A	; SAVE LAST BYTE FLAG
;
	INC	DE		; INCREMENT NUMBER OF BYTES TO READ BY ONE -- DUMMY READ BYTE
	LD	BC,0		; SET BYTE COUNTER
;
I2CPCF_RBL:
	PUSH	BC
	CALL	I2C_WAIT_FOR_PIN	; DO WE HAVE THE BUS?
	POP	BC
	JR	Z,I2CPCF_RB1	; YES
	CP	01H
	JR	Z,I2CPCF_RB3	; NO - LOST ARBITRATION
	JR	I2CPCF_RB2	; NO - TIMEOUT
;
I2CPCF_RB1:
	LD	A,(I2CPCF_STATUS)
	AND	I2CPCF_LRB


	; IS THIS THE SECOND TO LAST BYTE TO GO?

	PUSH	DE		; SAVE COUNT
	DEC	DE		; COUNT (DE) = NUMBER OF BYTES TO READ LESS 1
	EX	DE,HL		; SAVE POINTER, PUT COUNT IN DE
	XOR	A		; CLEAR CARRY FLAG
	SBC	HL,BC		; DOES BYTE COUNTER = HL (NUMBER OF BYTES TO READ LESS 1)
	EX	DE,HL		; RESTORE POINTER
	POP	DE		; RESTORE COUNT

				; Z = YES IT IS
				; NZ = NO IT ISN'T
	JR	NZ,I2CPCF_RB4
;
I2CPCF_RB4:
	LD	A,B		; IF FIRST READ DO A DUMMY
	OR	C		; READ OTHERWISE READ AND SAVE
	JR	NZ,I2CPCF_RB5

	IN	A,(I2CPCF_RS0)	; DUMMY READ
	JR	I2CPCF_RB6

I2CPCF_RB5:
	IN	A,(I2CPCF_RS0)	; READ AND SAVE
	LD	(HL),A
;
I2CPCF_RB6:	; HAVE WE DONE ALL?

	PUSH	DE		; SAVE COUNT
	EX	DE,HL		; SAVE POINTER, PUT COUNT IN DE
	XOR	A		; CLEAR CARRY FLAG
	SBC	HL,BC		; DOES BYTE COUNTER = HL (NUMBER OF BYTES TO READ)
	EX	DE,HL		; RESTORE POINTER
	POP	DE		; RESTORE COUNT
;
	INC	HL		; BUFFER POINTER
	INC	BC		; COUNT
;
	JR	NZ,I2CPCF_RBL	; REPEAT UNTIL COUNTS MATCH
	RET
;
I2CPCF_RB2:			; TIMEOUT
	CALL	I2C_STOP
	CALL	I2CPCF_TOERR
	RET
;
I2CPCF_RB3:			; LOST ARBITRATION
	CALL	I2CPCF_ARBERR
	RET
;
I2CPCF_LBF:
	.DB	0		; LAST BYTE FLAG
;
;-----------------------------------------------------------------------------
; READ ONE BYTE FROM I2C
; RETURNS DATA IN A
; Z FLAG SET IS ACKNOWLEDGE RECEIVED (CORRECT OPERATION)
;
I2C_READI2C:
	IN	A,(I2CPCF_RS1)	; READ S1 REGISTER
	BIT	7,A		; CHECK PIN STATUS
	JP	NZ,I2C_READI2C
	BIT	3,A		; CHECK LRB=0
	JP	NZ,I2CPCF_RDERR
	IN	A,(I2CPCF_RS0)	; GET DATA
	RET
;-----------------------------------------------------------------------------
;
; POLL THE BUS BUSY BIT TO DETERMINE IF BUS IS FREE.
; RETURN WITH A=00H/Z STATUS IF BUS IS FREE
; RETURN WITH A=FFH/NZ STATUS IF BUS IS BUSY
;
; AFTER RESET THE BUS BUSY BIT WILL BE SET TO 1 I.E. NOT BUSY
;
I2C_WAIT_FOR_BB:
	LD	HL,I2CPCF_BBTO
I2CPCF_WFBB0:
	IN	A,(I2CPCF_RS1)
	AND	I2CPCF_BB
	JR	NZ,I2CPCF_WFBB_OK	; BB=1 MEANS FREE (SEE COMMENT ABOVE)
	DEC	HL
	LD	A,H
	OR	L
	JR	NZ,I2CPCF_WFBB0	; REPEAT IF NOT TIMED OUT
	CPL		  	; RET NZ IF TIMEOUT
	RET
I2CPCF_WFBB_OK:
	; FLAGS HERE ARE NZ (FROM THE "AND I2CPCF_BB" CHECK THAT GOT US HERE), BUT
	; EVERY CALLER CHECKS NZ=FAILURE. FORCE Z ON THE WAY OUT (CP A DOESN'T
	; CHANGE A, ONLY SETS Z).
	CP	A
	RET
;
;-----------------------------------------------------------------------------
; DISPLAY ERROR MESSAGES
;
I2CPCF_RDERR:
	PUSH	HL
	LD	HL,I2CPCF_RDFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_INIERR:
	PUSH	HL
	LD	HL,I2CPCF_NOPCF
	JR	I2CPCF_PRTERR
;
I2CPCF_SETERR:
	PUSH	HL
	LD	HL,I2CPCF_WRTFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_REGERR:
	PUSH	HL
	LD	HL,I2CPCF_REGFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_CLKERR:
	PUSH	HL
	LD	HL,I2CPCF_CLKFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_IDLERR:
	PUSH	HL
	LD	HL,I2CPCF_IDLFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_ACKERR:
	PUSH	HL
	LD	HL,I2CPCF_ACKFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_RDBERR:
	PUSH	HL
	LD	HL,I2CPCF_RDBFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_TOERR:
	PUSH	HL
	LD	HL,I2CPCF_TOFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_ARBERR:
	PUSH	HL
	LD	HL,I2CPCF_ARBFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_PINERR:
	PUSH	HL
	LD	HL,I2CPCF_PINFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_BBERR:
	PUSH	HL
	LD	HL,I2CPCF_BBFAIL
	JR	I2CPCF_PRTERR
;
I2CPCF_PRTERR:
	CALL	PRTSTR
;	CALL	NEWLINE
	POP	HL
	; FORCE NZ THIS IS THE ERROR PATH
	OR	$FF
	RET
;
;
I2C_BBERR	.EQU	I2CPCF_BBERR
I2C_PINERR	.EQU	I2CPCF_PINERR
I2C_ACKERR	.EQU	I2CPCF_ACKERR
;
;-----------------------------------------------------------------------------
; DEBUG HELPER
;
#IF (1)
I2CPCF_DBG:
	PUSH	AF
	PUSH 	DE
	PUSH   	HL
	LD	A,'['
	CALL	COUT
	LD	HL,I2CPCF_DBGF
