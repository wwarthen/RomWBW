;
;==================================================================================================
; I2CEEPROM - I2C SERIAL EEPROM DIO DRIVER (24LCXXX VIA I2CPCF/I2CBIT)
;==================================================================================================
;
; TREATS THE I2C SERIAL EEPROM AS A RAW BLOCK DEVICE, ONE BLOCK PER
; DIOREAD/DIOWRITE CALL, BLOCK SIZE FIXED AT COMPILE TIME PER UNIT, SHOULD
; MATCH EACH CHIP'S PHYSICAL PAGE SIZE SO WRITES NEVER STRADDLE A PAGE
; BOUNDARY. NOT WIRED TO A CP/M DRIVE LETTER, THESE UNITS NEVER APPEAR IN
; THE BIOS DISK MAP, ONLY REACHABLE BY A PROGRAM CALLING
; BF_DIOSEEK/BF_DIOREAD/BF_DIOWRITE DIRECTLY VIA RST 08.
;
; UP TO 8 FIXED UNITS, ONE PER 24CXX CHIP-SELECT ADDRESS $50-$57
; EACH SLOT IS INDEPENDENTLY ENABLED AND SIZED AT COMPILE TIME
; DISABLED SLOT COSTS NOTHING, ITS CFGTBL ENTRY SIMPLY DOESN'T EXIST
;
; I2CEEPROM_MKADR USES EACH UNIT'S OWN SHIFT TO TURN A BLOCK NUMBER INTO A
; BYTE ADDRESS, REAL 24CXXX PAGE SIZES ARE ALWAYS A POWER OF TWO SO A
; SHIFT COVERS IT.
;
; WITH I2CEEPROMDETECT, EVERY SLOT NOT MANUALLY ENABLED (AND SET IN
; I2CEEPROMDETMASK) GETS AN ENTRY WITH SHIFT=I2CEEPROM_AUTO. INIT PROBES IT,
; SKIPS IT SILENTLY IF ABSENT, OTHERWISE I2CEEPROM_DETECT FILLS IN THE REAL
; SHIFT/BLKCNT BEFORE THE UNIT IS REGISTERED.
;
I2CEEPROM_AUTO		.EQU	$FF	; SHIFT VALUE MARKING A SLOT FOR AUTODETECT
I2CEEPROM_CFGSIZ	.EQU	7	; BYTES PER CFG TABLE ENTRY
					; DEV#
					; BLK# LO
					; BLK# HI
					; I2C ADDR
					; SHIFT
					; BLKCNT LO
					; BLKCNT HI
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_I2CEEPROM	.EQU	$
;
	.DW	SIZ_I2CEEPROM		; MODULE SIZE
	.DW	I2CEEPROM_INITPHASE	; ADR OF INIT PHASE HANDLER
;
I2CEEPROM_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,I2CEEPROM_INIT		; DO INIT
	RET				; DONE
;
; PER-UNIT CONFIG/STATE, ONE 7-BYTE ENTRY PER ENABLED SLOT, TERMINATED BY
; A LONE $FF, DEV# (BYTE 0) CAN NEVER LEGITIMATELY BE $FF
;
; A MANUAL SLOT (EN=TRUE) GETS ITS FIXED SHIFT/BLKCNT, AN AUTODETECT SLOT
; GETS SHIFT=I2CEEPROM_AUTO AND BLKCNT=0. TRUE IS ALL ONES, SO EN & X
; PASSES X THROUGH ONLY FOR A MANUAL SLOT.
;
#DEFINE I2CEEPROM_SLOT(ADR,EN,SHIFT,BLKCNT) \
#defcont \	.DB	0 \
#defcont \	.DW	0 \
#defcont \	.DB	ADR \
#defcont \	.DB	(EN & SHIFT) | (~EN & I2CEEPROM_AUTO) \
#defcont \	.DW	EN & BLKCNT \
#defcont \I2CEEPROM_BADSHIFT	.SET	I2CEEPROM_BADSHIFT | (EN & (SHIFT > 7))
;
I2CEEPROM_BADSHIFT	.EQU	0	; SET BY ANY MANUAL SLOT WITH SHIFT > 7
I2CEEPROM_CFGTBL:
#IF (I2CEEPROMADR0ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $01))
	I2CEEPROM_SLOT($50,I2CEEPROMADR0ENABLE,I2CEEPROMSHIFT0,I2CEEPROMBLKCNT0)
#ENDIF
#IF (I2CEEPROMADR1ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $02))
	I2CEEPROM_SLOT($51,I2CEEPROMADR1ENABLE,I2CEEPROMSHIFT1,I2CEEPROMBLKCNT1)
#ENDIF
#IF (I2CEEPROMADR2ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $04))
	I2CEEPROM_SLOT($52,I2CEEPROMADR2ENABLE,I2CEEPROMSHIFT2,I2CEEPROMBLKCNT2)
#ENDIF
#IF (I2CEEPROMADR3ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $08))
	I2CEEPROM_SLOT($53,I2CEEPROMADR3ENABLE,I2CEEPROMSHIFT3,I2CEEPROMBLKCNT3)
#ENDIF
#IF (I2CEEPROMADR4ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $10))
	I2CEEPROM_SLOT($54,I2CEEPROMADR4ENABLE,I2CEEPROMSHIFT4,I2CEEPROMBLKCNT4)
#ENDIF
#IF (I2CEEPROMADR5ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $20))
	I2CEEPROM_SLOT($55,I2CEEPROMADR5ENABLE,I2CEEPROMSHIFT5,I2CEEPROMBLKCNT5)
#ENDIF
#IF (I2CEEPROMADR6ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $40))
	I2CEEPROM_SLOT($56,I2CEEPROMADR6ENABLE,I2CEEPROMSHIFT6,I2CEEPROMBLKCNT6)
#ENDIF
#IF (I2CEEPROMADR7ENABLE | (I2CEEPROMDETECT & I2CEEPROMDETMASK & $80))
	I2CEEPROM_SLOT($57,I2CEEPROMADR7ENABLE,I2CEEPROMSHIFT7,I2CEEPROMBLKCNT7)
#ENDIF
	.DB	$FF			; END OF TABLE MARKER
;
#IF (I2CEEPROMDETECT)
	DEVECHO	"I2CEEPROM: AUTODETECT ON\n"
#ENDIF
#IF (I2CEEPROM_BADSHIFT)
	.ECHO	"*** I2CEEPROM: A MANUAL SLOT SHIFT EXCEEDS 7 (128-BYTE STAGEBUF) ***\n"
	!!!
#ENDIF
;
I2CEEPROM_DEVNUM:
	.DB	0			; NEXT DEVICE NUMBER TO ASSIGN, WORKING VAR
;
I2CEEPROM_INIT:
	XOR	A
	LD	(I2CEEPROM_DEVNUM),A
	LD	IY,I2CEEPROM_CFGTBL	; IY := START OF CFG TABLE
I2CEEPROM_INIT1:
	LD	A,(IY+0)		; LOAD FIRST BYTE TO CHECK FOR END
	CP	$FF			; CHECK FOR END OF TABLE VALUE
	JP	Z,I2CEEPROM_INIT4	; END OF TABLE, DONE
;
#IF (I2CEEPROMDETECT)
	LD	A,(IY+4)
	CP	I2CEEPROM_AUTO		; AUTODETECT SLOT?
	JP	Z,I2CEEPROM_INITAUTO
#ENDIF
	CALL	I2CEEPROM_NEWDEV
	CALL	I2CEEPROM_PRTADR
	CALL	I2CEEPROM_PRTSIZE
	LD	A,(I2C_FAIL_FLAG)
	OR	A
	JR	Z,I2CEEPROM_INIT1A
	PRTS("I2C FAILURE$")
	JR	I2CEEPROM_INIT3B
I2CEEPROM_INIT1A:
	LD	A,(IY+3)
	CALL	I2CEEPROM_PROBEADR
	JR	NZ,I2CEEPROM_INIT2
	PRTS("FIXED$")
	JR	I2CEEPROM_INIT3
I2CEEPROM_INIT2:
	PRTS("NOT FOUND$")
	JR	I2CEEPROM_INIT3B	; ABSENT, SKIP DIO_ADDENT, DON'T REGISTER A PHANTOM UNIT
I2CEEPROM_INIT3:
	PUSH	IY
	POP	DE			; DE := THIS UNIT'S CFG PTR
	LD	BC,I2CEEPROM_FNTBL	; BC := DRIVER FUNC TABLE ADDRESS
	CALL	DIO_ADDENT		; ADD ENTRY TO GLOBAL DISK TABLE
I2CEEPROM_INIT3B:
;
	LD	DE,I2CEEPROM_CFGSIZ
	ADD	IY,DE			; ADVANCE TO NEXT CFG SLOT
	JP	I2CEEPROM_INIT1
I2CEEPROM_INIT4:
	XOR	A			; SIGNAL SUCCESS
	RET
;
#IF (I2CEEPROMDETECT)
;
; AUTODETECT SLOT, NO BANNER LINE AT ALL UNLESS A CHIP ANSWERS
;
I2CEEPROM_INITAUTO:
	LD	A,(IY+3)
	CALL	I2CEEPROM_PROBEADR
	JR	NZ,I2CEEPROM_INIT3B	; ABSENT, SKIP SILENTLY
	CALL	I2CEEPROM_NEWDEV
	CALL	I2CEEPROM_PRTADR
	CALL	I2CEEPROM_DETECT	; FILLS SHIFT/BLKCNT, NZ=SIZE UNKNOWN
	PUSH	AF
	CALL	I2CEEPROM_PRTSIZE
	POP	AF
	JR	NZ,I2CEEPROM_INITAUTO1
	PRTS("DETECTED$")
	JR	I2CEEPROM_INIT3
I2CEEPROM_INITAUTO1:
	PRTS("SIZE UNKNOWN USING 4KB$")
	JR	I2CEEPROM_INIT3
;
#ENDIF
;
; ASSIGN THE NEXT DEVICE NUMBER TO THIS UNIT
;
I2CEEPROM_NEWDEV:
	LD	A,(I2CEEPROM_DEVNUM)
	LD	(IY+0),A
	INC	A
	LD	(I2CEEPROM_DEVNUM),A
	RET
;
I2CEEPROM_PRTADR:
	CALL	NEWLINE			; FORMATTING
	PRTS("I2CEEPROM: $")
	PRTS("I2C ADDR=0x$")
	LD	A,(IY+3)
	JP	PRTHEXBYTE
;
I2CEEPROM_PRTSIZE:
	PRTS(" BLKSIZ=$")
	LD	B,(IY+4)
	CALL	I2CEEPROM_SHIFTTOBYTE	; A := 1 << SHIFT (MOD 256)
	CALL	PRTDECB
	PRTS(" BLKCNT=$")
	LD	L,(IY+5)
	LD	H,(IY+6)
	LD	DE,0
	CALL	PRTDEC
	JP	PC_SPACE
;
; PROBE FOR A CHIP AT THE GIVEN I2C ADDRESS, JUST CHECKS FOR AN I2C ACK
; RETURNS Z=PRESENT, NZ=ABSENT/BUS ERROR
;
I2CEEPROM_PROBEADR:
	SLA	A			; WRITE-MODE I2C ADDRESS (R/W BIT=0)
	LD	E,A
	CALL	I2C_BF_START
	PUSH	AF
	LD	E,0
	CALL	I2C_BF_STOP
	POP	AF
	RET
;
; RETURN THIS UNIT'S WRITE-MODE / READ-MODE I2C ADDRESS IN A
;
I2CEEPROM_UNIT_WADR:
	LD	A,(IY+3)
	SLA	A			; R/W BIT = 0
	RET
I2CEEPROM_UNIT_RADR:
	LD	A,(IY+3)
	SLA	A
	OR	1			; R/W BIT = 1
	RET
;
; DRIVER FUNCTION TABLE
;
I2CEEPROM_FNTBL:
	.DW	I2CEEPROM_STATUS
	.DW	I2CEEPROM_RESET
	.DW	I2CEEPROM_SEEK
	.DW	I2CEEPROM_READ
	.DW	I2CEEPROM_WRITE
	.DW	I2CEEPROM_VERIFY
	.DW	I2CEEPROM_FORMAT
	.DW	I2CEEPROM_DEVICE
	.DW	I2CEEPROM_MEDIA
	.DW	I2CEEPROM_DEFMED
	.DW	I2CEEPROM_CAP
	.DW	I2CEEPROM_GEOM
#IF (($ - I2CEEPROM_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID I2CEEPROM FUNCTION TABLE ***\n"
#ENDIF
;
; NOT MEANINGFUL FOR THIS DEVICE, FIXED, NEVER BDOS-MOUNTED
;
I2CEEPROM_VERIFY:
I2CEEPROM_FORMAT:
I2CEEPROM_DEFMED:
I2CEEPROM_GEOM:
	SYSCHKERR(ERR_NOTIMPL)
	RET
;
; CHIP IS ALWAYS PRESENT/READY, NOTHING TO RESET
;
I2CEEPROM_STATUS:
I2CEEPROM_RESET:
	XOR	A
	RET
;
I2CEEPROM_DEVICE:
	LD	D,DIODEV_I2CEEPROM	; D := DEVICE TYPE
	LD	E,(IY+0)		; E := PHYSICAL DEVICE NUMBER
	LD	C,%00011101		; C := ATTRIBUTES, BIT 4=LBA CAPABLE, BITS 3-0=13 (EEPROM,
					; ITS OWN TYPE CODE, SEE PS_DTEE IN INVNTDEV.ASM)
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,(IY+3)		; L := THIS UNIT'S I2C ADDRESS
	XOR	A
	RET
;
I2CEEPROM_MEDIA:
	LD	E,MID_NONE		; NOT "ONLINE" MEDIA
	LD	D,0			; D:0=0 MEANS NO MEDIA CHANGE
	LD	A,ERR_NOMEDIA		; NO MEDIA ERROR, KEEPS CBIOS FROM
					; AUTO ASSIGNING THIS A CP/M DRIVE LETTER
	OR	A
	RET
;
; RETURN DE:HL=BLOCK COUNT, BC=BLOCK SIZE, PER THIS UNIT'S OWN CONFIG.
;
I2CEEPROM_CAP:
	LD	DE,0
	LD	L,(IY+5)		; BLOCK COUNT LO
	LD	H,(IY+6)		; BLOCK COUNT HI
	LD	B,(IY+4)		; SHIFT COUNT
	CALL	I2CEEPROM_SHIFTTOBYTE	; A := 1 << B (MOD 256)
	LD	C,A
	LD	B,0
	OR	A
	JR	NZ,I2CEEPROM_CAP1
	INC	B
I2CEEPROM_CAP1:
	XOR	A
	RET
;
; ENTRY: HL = BLOCK NUMBER (0 TO THIS UNIT'S BLKCNT-1)
;
I2CEEPROM_SEEK:
	LD	(IY+1),L
	LD	(IY+2),H
	XOR	A
	RET
;
;--------------------------------------------------------------------------------------------------
; COMPUTE I2C BYTE ADDRESS FOR CURRENT BLOCK (BLOCK# << THIS UNIT'S SHIFT)
; RETURNS BIG-ENDIAN BYTES IN I2CEEPROM_ADRBUF (AS THE 24LCXXX EXPECTS)
;--------------------------------------------------------------------------------------------------
;
I2CEEPROM_MKADR:
	LD	L,(IY+1)		; CURRENT BLOCK NUMBER
	LD	H,(IY+2)
	LD	B,(IY+4)		; THIS UNIT'S SHIFT COUNT
I2CEEPROM_MKADR1:
	LD	A,B
	OR	A
	JR	Z,I2CEEPROM_MKADR2
	ADD	HL,HL
	DEC	B
	JR	I2CEEPROM_MKADR1
I2CEEPROM_MKADR2:
	LD	A,H
	LD	(I2CEEPROM_ADRBUF+0),A	; ADDRESS HIGH BYTE
	LD	A,L
	LD	(I2CEEPROM_ADRBUF+1),A	; ADDRESS LOW BYTE
	RET
;
; A := 1 << B (SHIFT COUNT IN B)
;
I2CEEPROM_SHIFTTOBYTE:
	PUSH	HL
	LD	HL,1
I2CEEPROM_STB1:
	LD	A,B
	OR	A
	JR	Z,I2CEEPROM_STB2
	ADD	HL,HL
	DEC	B
	JR	I2CEEPROM_STB1
I2CEEPROM_STB2:
	LD	A,L
	POP	HL
	RET
;
;--------------------------------------------------------------------------------------------------
; ISSUE START + WRITE-MODE ADDRESS, THEN SEND THE 2-BYTE MEMORY POINTER.
; LEAVES THE BUS IN WRITE MODE, READY FOR EITHER DATA BYTES (WRITE) OR A
; REPEATED START INTO READ MODE.
; RETURNS Z=OK, NZ=ERROR
;--------------------------------------------------------------------------------------------------
;
I2CEEPROM_SETPTR:
	CALL	I2CEEPROM_MKADR
I2CEEPROM_SETPTR1:
	CALL	I2CEEPROM_UNIT_WADR
	LD	E,A
	CALL	I2C_BF_START
	RET	NZ
;
	LD	A,(I2CEEPROM_ADRBUF+0)	; MEMORY ADDRESS HIGH BYTE
	LD	E,A
	CALL	I2C_BF_WRITE
	RET	NZ
;
	LD	A,(I2CEEPROM_ADRBUF+1)	; MEMORY ADDRESS LOW BYTE
	LD	E,A
	CALL	I2C_BF_WRITE
	RET	NZ
;
	XOR	A
	RET
;
;--------------------------------------------------------------------------------------------------
; ENTRY: HL = BUFFER ADDRESS
;--------------------------------------------------------------------------------------------------
;
I2CEEPROM_READ:
	; STASH CALLER'S BUFFER ADDR/BANK
	LD	(I2CEEPROM_CALLERBUF),HL
	LD	A,D
	LD	(I2CEEPROM_CALLERBNK),A
	CALL	I2CEEPROM_SETPTR	; SET MEMORY POINTER (WRITE MODE)
	JP	NZ,I2CEEPROM_READ_ERR2
;
	CALL	I2CEEPROM_UNIT_RADR
	LD	E,A
	CALL	I2C_BF_REPSTART		; REPEATED START, SWITCH TO READ DIRECTION
	JP	NZ,I2CEEPROM_READ_ERR2
;
	LD	HL,I2CEEPROM_STAGEBUF	; READ INTO OUR STAGING BUFFER
	LD	B,(IY+4)
	CALL	I2CEEPROM_SHIFTTOBYTE
	LD	B,A
I2CEEPROM_READ1:
	LD	A,B
	CP	1			; LAST BYTE?
	LD	E,0
	JR	NZ,I2CEEPROM_READ2
	LD	E,1			; NACK THE FINAL BYTE
I2CEEPROM_READ2:
	PUSH	HL			; I2C_BF_READ RETURNS ITS BYTE IN L
	CALL	I2C_BF_READ
	JR	NZ,I2CEEPROM_READ_POPFAIL
	LD	A,L			; CAPTURE THE BYTE BEFORE HL IS RESTORED
	POP	HL
	LD	(HL),A
	INC	HL
	DJNZ	I2CEEPROM_READ1
;
	LD	E,0
	CALL	I2C_BF_STOP
;
	; COPY THE STAGING BUFFER TO THE CALLER'S REAL BUFFER/BANK
	LD	A,BID_BIOS		; SOURCE BANK IS US
	LD	(HB_SRCBNK),A
	LD	A,(I2CEEPROM_CALLERBNK)	; DEST BANK IS THE CALLER'S
	LD	(HB_DSTBNK),A
	LD	HL,I2CEEPROM_STAGEBUF
	LD	DE,(I2CEEPROM_CALLERBUF)
	LD	B,(IY+4)
	CALL	I2CEEPROM_SHIFTTOBYTE
	LD	C,A
	LD	B,0
	OR	A
	JR	NZ,I2CEEPROM_READ4
	INC	B
I2CEEPROM_READ4:
	CALL	HBX_BNKCPY
;
	CALL	I2CEEPROM_BUMPBLK
	XOR	A
	RET
;
I2CEEPROM_READ_POPFAIL:
	POP	HL			; DISCARD, NOT WRITING THIS BYTE
I2CEEPROM_READ_ERR2:
	PUSH	AF
	LD	E,0
	CALL	I2C_BF_STOP
	POP	AF
	LD	A,ERR_IO
	OR	A
	RET
;
;--------------------------------------------------------------------------------------------------
; ENTRY: HL = BUFFER ADDRESS
;--------------------------------------------------------------------------------------------------
;
I2CEEPROM_WRITE:
	; COPY THE CALLER'S REAL BUFFER INTO OUR OWN STAGING BUFFER
	LD	A,D			; CALLER'S BUFFER BANK
	LD	(HB_SRCBNK),A
	LD	A,BID_BIOS
	LD	(HB_DSTBNK),A
	LD	DE,I2CEEPROM_STAGEBUF
	LD	B,(IY+4)
	CALL	I2CEEPROM_SHIFTTOBYTE
	LD	C,A
	LD	B,0
	OR	A
	JR	NZ,I2CEEPROM_WRITE0
	INC	B
I2CEEPROM_WRITE0:
	CALL	HBX_BNKCPY		; HL (CALLER BUF) -> DE (STAGEBUF)
;
	CALL	I2CEEPROM_SETPTR	; SET MEMORY POINTER (WRITE MODE)
	JR	NZ,I2CEEPROM_WRITE_ERR2
;
	LD	HL,I2CEEPROM_STAGEBUF	; WRITE FROM OUR STAGING BUFFER
	LD	B,(IY+4)
	CALL	I2CEEPROM_SHIFTTOBYTE
	LD	B,A
I2CEEPROM_WRITE1:
	LD	A,(HL)
	LD	E,A
	PUSH	HL
	PUSH	BC
	CALL	I2C_BF_WRITE
	POP	BC
	POP	HL
	JR	NZ,I2CEEPROM_WRITE_ERR2
	INC	HL
	DJNZ	I2CEEPROM_WRITE1
;
	LD	E,0
	CALL	I2C_BF_STOP
	CALL	I2CEEPROM_WRITE_WAIT	; WAIT FOR THE CHIP'S WRITE CYCLE
	RET	NZ
;
	CALL	I2CEEPROM_BUMPBLK
	XOR	A
	RET
;
I2CEEPROM_WRITE_ERR2:
	PUSH	AF
	LD	E,0
	CALL	I2C_BF_STOP
	POP	AF
	LD	A,ERR_IO
	OR	A
	RET
;
; WHILE THE CHIP IS COMMITTING A PAGE WRITE, IT NAKS ANY NEW START
; POLL UNTIL IT ACKS OR WE GIVE UP
;
I2CEEPROM_WRITE_WAIT:
	LD	B,0			; TRY 256 TIMES
I2CEEPROM_WRITE_WAIT1:
	PUSH	BC
	CALL	I2CEEPROM_UNIT_WADR
	LD	E,A
	CALL	I2C_BF_START
	PUSH	AF
	LD	E,0
	CALL	I2C_BF_STOP
	POP	AF
	POP	BC
	JR	Z,I2CEEPROM_WRITE_WAIT2	; ACKED, CHIP IS READY
	DJNZ	I2CEEPROM_WRITE_WAIT1
	LD	A,ERR_IO		; GAVE UP
	OR	A
	RET
I2CEEPROM_WRITE_WAIT2:
	XOR	A
	RET
;
; ADVANCE TO THE NEXT BLOCK
;
I2CEEPROM_BUMPBLK:
	LD	L,(IY+1)
	LD	H,(IY+2)
	INC	HL
	LD	(IY+1),L
	LD	(IY+2),H
	RET
;
#IF (I2CEEPROMDETECT)
;
;--------------------------------------------------------------------------------------------------
; AUTODETECT. NO 24CXX CHIP CAN REPORT ITS OWN SIZE, BUT ITS ADDRESS
; COUNTER WRAPS AT ITS REAL CAPACITY, SO A READ AT A CANDIDATE BOUNDARY
; RETURNS THE SAME BYTES AS ADDRESS 0 ON A CHIP OF EXACTLY THAT SIZE.
; A UNIFORM WINDOW AT ADDRESS 0 (BLANK $FF, ALL $00) PROVES NOTHING, SO AN
; 8 BYTE SIGNATURE IS WRITTEN THERE FIRST AND THE ORIGINAL BYTES ARE PUT
; BACK AFTERWARDS. A CHIP WITH REAL DATA AT ADDRESS 0 IS NEVER WRITTEN.
; RETURNS Z=SIZE FOUND, NZ=SIZE UNKNOWN (SMALLEST CANDIDATE APPLIED)
;--------------------------------------------------------------------------------------------------
;
I2CEEPROM_DETECT:
	PUSH	IX
	LD	IX,I2CEEPROM_DETTBL	; SMALLEST CANDIDATE UNTIL PROVEN OTHERWISE
	CALL	I2CEEPROM_DETAPPLY
;
	LD	HL,0
	LD	DE,I2CEEPROM_DETBASE
	LD	B,I2CEEPROM_DETLEN
	CALL	I2CEEPROM_RAWREAD
	JR	NZ,I2CEEPROM_DETECT_END	; SIZE UNKNOWN
	CALL	I2CEEPROM_ISUNIFORM
	JR	Z,I2CEEPROM_DETECT_SIG
;
	LD	HL,I2CEEPROM_DETBASE	; REAL DATA, READ-ONLY SCAN
	LD	(I2CEEPROM_DETREF),HL
	LD	A,I2CEEPROM_DETLEN
	LD	(I2CEEPROM_DETN),A
	CALL	I2CEEPROM_DETSCAN
	JR	I2CEEPROM_DETECT_END
;
I2CEEPROM_DETECT_SIG:
	LD	A,1
	LD	(I2CEEPROM_DETRES),A	; SIZE UNKNOWN UNTIL THE SCAN SUCCEEDS
	LD	HL,0
	LD	DE,I2CEEPROM_DETSIG
	LD	B,I2CEEPROM_SIGLEN
	CALL	I2CEEPROM_RAWWRITE
	JR	NZ,I2CEEPROM_DETECT_RST
;
	LD	HL,0			; READ IT BACK, WP PIN HIGH SILENTLY
	LD	DE,I2CEEPROM_DETCAND	; IGNORES THE WRITE
	LD	B,I2CEEPROM_SIGLEN
	CALL	I2CEEPROM_RAWREAD
	JR	NZ,I2CEEPROM_DETECT_RST
	LD	HL,I2CEEPROM_DETSIG
	LD	B,I2CEEPROM_SIGLEN
	CALL	I2CEEPROM_CMPCAND
	JR	NZ,I2CEEPROM_DETECT_RST
;
	LD	HL,I2CEEPROM_DETSIG
	LD	(I2CEEPROM_DETREF),HL
	LD	A,I2CEEPROM_SIGLEN
	LD	(I2CEEPROM_DETN),A
	CALL	I2CEEPROM_DETSCAN
	JR	NZ,I2CEEPROM_DETECT_RST
	XOR	A
	LD	(I2CEEPROM_DETRES),A
;
I2CEEPROM_DETECT_RST:
	LD	HL,0			; PUT THE ORIGINAL BYTES BACK
	LD	DE,I2CEEPROM_DETBASE
	LD	B,I2CEEPROM_SIGLEN
	CALL	I2CEEPROM_RAWWRITE
	LD	A,(I2CEEPROM_DETRES)
	OR	A
;
I2CEEPROM_DETECT_END:
	POP	IX
	RET
;
; READ THE WINDOW AT EACH CANDIDATE BOUNDARY AND COMPARE IT AGAINST
; DETREF/DETN. THE FIRST MATCH IS THE SIZE, NO MATCH BELOW 64KB MEANS
; 24C512. RETURNS Z=SIZE APPLIED, NZ=BUS ERROR, NOTHING APPLIED.
;
I2CEEPROM_DETSCAN:
	LD	IX,I2CEEPROM_DETTBL
	LD	B,I2CEEPROM_DETTBLCNT
I2CEEPROM_DETSCAN1:
	PUSH	BC
	LD	L,(IX+0)		; BOUNDARY ADDRESS
	LD	H,(IX+1)
	LD	DE,I2CEEPROM_DETCAND
	LD	A,(I2CEEPROM_DETN)
	LD	B,A
	CALL	I2CEEPROM_RAWREAD
	JR	NZ,I2CEEPROM_DETSCAN_ERR
	LD	HL,(I2CEEPROM_DETREF)
	LD	A,(I2CEEPROM_DETN)
	LD	B,A
	CALL	I2CEEPROM_CMPCAND
	POP	BC
	JR	Z,I2CEEPROM_DETSCAN2	; WRAPS HERE, THIS IS THE SIZE
	LD	DE,I2CEEPROM_DETENTSIZ
	ADD	IX,DE
	DJNZ	I2CEEPROM_DETSCAN1
I2CEEPROM_DETSCAN2:
	CALL	I2CEEPROM_DETAPPLY
	XOR	A
	RET
I2CEEPROM_DETSCAN_ERR:
	POP	BC
	OR	$FF
	RET
;
; COPY CANDIDATE ENTRY (IX) INTO THIS UNIT'S CFG ENTRY (IY)
;
I2CEEPROM_DETAPPLY:
	LD	A,(IX+2)
	LD	(IY+5),A		; BLKCNT LO
	LD	A,(IX+3)
	LD	(IY+6),A		; BLKCNT HI
	LD	A,(IX+4)
	LD	(IY+4),A		; SHIFT
	RET
;
; Z = ALL DETLEN BYTES OF DETBASE ARE THE SAME VALUE
;
I2CEEPROM_ISUNIFORM:
	LD	HL,I2CEEPROM_DETBASE
	LD	A,(HL)
	LD	B,I2CEEPROM_DETLEN - 1
I2CEEPROM_ISUNIFORM1:
	INC	HL
	CP	(HL)
	RET	NZ
	DJNZ	I2CEEPROM_ISUNIFORM1
	RET
;
; Z = FIRST B BYTES OF DETCAND MATCH (HL)
;
I2CEEPROM_CMPCAND:
	LD	DE,I2CEEPROM_DETCAND
I2CEEPROM_CMPCAND1:
	LD	A,(DE)
	CP	(HL)
	RET	NZ
	INC	HL
	INC	DE
	DJNZ	I2CEEPROM_CMPCAND1
	RET
;
; SET THE CHIP'S MEMORY POINTER TO THE RAW BYTE ADDRESS IN HL
;
I2CEEPROM_SETPTRHL:
	LD	A,H
	LD	(I2CEEPROM_ADRBUF+0),A
	LD	A,L
	LD	(I2CEEPROM_ADRBUF+1),A
	JP	I2CEEPROM_SETPTR1
;
; READ B BYTES FROM RAW BYTE ADDRESS HL INTO DE (BIOS BANK)
; RETURNS Z=OK, NZ=ERROR
;
I2CEEPROM_RAWREAD:
	PUSH	BC
	PUSH	DE
	CALL	I2CEEPROM_SETPTRHL
	JR	NZ,I2CEEPROM_RAWREAD_ERR
	CALL	I2CEEPROM_UNIT_RADR
	LD	E,A
	CALL	I2C_BF_REPSTART		; REPEATED START, SWITCH TO READ DIRECTION
	JR	NZ,I2CEEPROM_RAWREAD_ERR
	POP	HL			; HL := DEST
	POP	BC
I2CEEPROM_RAWREAD1:
	LD	E,0
	LD	A,B
	DEC	A			; LAST BYTE?
	JR	NZ,I2CEEPROM_RAWREAD2
	INC	E			; NACK THE FINAL BYTE
I2CEEPROM_RAWREAD2:
	PUSH	HL
	PUSH	BC
	CALL	I2C_BF_READ		; A=STATUS, L=DATA BYTE
	LD	A,L			; LD/POP LEAVE THE STATUS FLAGS ALONE
	POP	BC
	POP	HL
	JP	NZ,I2CEEPROM_READ_ERR2
	LD	(HL),A
	INC	HL
	DJNZ	I2CEEPROM_RAWREAD1
	LD	E,0
	CALL	I2C_BF_STOP
	XOR	A
	RET
I2CEEPROM_RAWREAD_ERR:
	POP	DE
	POP	BC
	JP	I2CEEPROM_READ_ERR2
;
; WRITE B BYTES FROM DE (BIOS BANK) TO RAW BYTE ADDRESS HL, WITHIN ONE PAGE
; RETURNS Z=OK, NZ=ERROR
;
I2CEEPROM_RAWWRITE:
	PUSH	BC
	PUSH	DE
	CALL	I2CEEPROM_SETPTRHL
	POP	HL			; HL := SOURCE
	POP	BC
	JP	NZ,I2CEEPROM_WRITE_ERR2
I2CEEPROM_RAWWRITE1:
	LD	E,(HL)
	PUSH	HL
	PUSH	BC
	CALL	I2C_BF_WRITE
	POP	BC
	POP	HL
	JP	NZ,I2CEEPROM_WRITE_ERR2
	INC	HL
	DJNZ	I2CEEPROM_RAWWRITE1
	LD	E,0
	CALL	I2C_BF_STOP
	JP	I2CEEPROM_WRITE_WAIT	; WAIT FOR THE CHIP'S WRITE CYCLE
;
; CANDIDATE SIZES, SMALLEST FIRST. EACH ENTRY IS THE WRAP BOUNDARY TO TEST,
; THEN THE BLKCNT AND SHIFT TO APPLY. THE LAST ENTRY IS NEVER TESTED, 64KB
; CAN'T BE ADDRESSED, IT'S WHAT A CHIP THAT NEVER WRAPS GETS.
;
I2CEEPROM_DETENTSIZ	.EQU	5
;
I2CEEPROM_DETTBL:
	.DW	$1000, 128		; 24C32:   4096 BYTES
	.DB	5
	.DW	$2000, 256		; 24C64:   8192 BYTES
	.DB	5
	.DW	$4000, 256		; 24C128: 16384 BYTES
	.DB	6
	.DW	$8000, 512		; 24C256: 32768 BYTES
	.DB	6
	.DW	0, 512			; 24C512: 65536 BYTES
	.DB	7
I2CEEPROM_DETTBLCNT	.EQU	4	; ENTRIES ACTUALLY TESTED
;
I2CEEPROM_DETLEN	.EQU	16	; READ-ONLY COMPARE WINDOW
I2CEEPROM_SIGLEN	.EQU	8
;
I2CEEPROM_DETSIG:
	.DB	$AA,$55,$55,$AA,$11,$88,$88,$11
I2CEEPROM_DETBASE:
	.FILL	I2CEEPROM_DETLEN,0	; WINDOW AT ADDRESS 0, ALSO THE RESTORE COPY
I2CEEPROM_DETCAND:
	.FILL	I2CEEPROM_DETLEN,0	; WINDOW AT A CANDIDATE BOUNDARY
I2CEEPROM_DETREF:
	.DW	0			; WHAT DETSCAN COMPARES AGAINST
I2CEEPROM_DETN:
	.DB	0			; HOW MANY BYTES DETSCAN COMPARES
I2CEEPROM_DETRES:
	.DB	0			; SIGNATURE PATH RESULT, 0=SIZE FOUND
;
#ENDIF
;
I2CEEPROM_ADRBUF:
	.FILL	2,0			; MEMORY ADDRESS BUFFER
;
; BANK SUPPORT: HBX_INVOKE SWITCHES TO THE BIOS BANK BEFORE CALLING
; ANY DRIVER, SO I2CEEPROM_READ/WRITE MUST NOT TOUCH THE CALLER'S BUFFER
; ADDRESS DIRECTLY, THEY STAGE THROUGH THIS BUFFER AND COPY VIA
; HBX_BNKCPY INSTEAD.
;
I2CEEPROM_STAGEBUF:
	.FILL	128,0			; STAGING BUFFER, BIOS BANK. SIZED FOR
					; SHIFT=7 (BLKSIZ=128), THE LARGEST
					; SHIFT THE CFGTBL !!! GUARD ALLOWS
I2CEEPROM_CALLERBUF:
	.DW	0			; CALLER'S REAL BUFFER ADDRESS (READ ONLY)
I2CEEPROM_CALLERBNK:
	.DB	0			; CALLER'S REAL BUFFER BANK (READ ONLY)
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_I2CEEPROM	.EQU	$
SIZ_I2CEEPROM	.EQU	END_I2CEEPROM - ORG_I2CEEPROM
;
	MEMECHO	"I2CEEPROM occupies "
	MEMECHO	SIZ_I2CEEPROM
	MEMECHO	" bytes.\n"
